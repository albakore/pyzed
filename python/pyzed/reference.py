def entries(lang: Optional[str] = None) -> List[Entry]:
    """Every page of the reference, in class-list order (designer controls first, then the library)."""
    lang = _language(lang)
    out: List[Entry] = []
    providers = _all_providers()
    for provider in [*providers[1:-1], providers[0], providers[-1]]:
        out += provider.entries(lang)
    return out


def sections(lang: Optional[str] = None) -> List[Tuple[str, List[Tuple[str, List[Entry]]]]]:
    """The class list: ``[(section, [(group, [entries]), ...]), ...]`` in order."""
    out: List[Tuple[str, List[Tuple[str, List[Entry]]]]] = []
    for entry in entries(lang):
        if entry.kind == "page":
            continue
        if not out or out[-1][0] != entry.section:
            out.append((entry.section, []))
        groups = out[-1][1]
        if not groups or groups[-1][0] != entry.group:
            groups.append((entry.group, []))
        groups[-1][1].append(entry)
    return out


def search(query: str, lang: Optional[str] = None, limit: int = 60) -> List[Entry]:
    """Entries matching ``query``: exact names first, then names that start with it, then the rest.

    Every word must appear in the title, group or summary (``"tab bar"`` finds ``ui.tab_bar``).
    """
    words = [w for w in re.split(r"[\s_.]+", query.lower().strip()) if w]
    if not words:
        return []
    needle = query.lower().strip()
    scored = []
    for i, entry in enumerate(entries(lang)):
        title = entry.title.lower()
        short = title.rsplit(".", 1)[-1]
        hay = f"{title} {entry.id.lower()} {entry.group.lower()} {entry.summary.lower()}"
        if not all(w in hay for w in words):
            continue
        if needle in (title, short, entry.id.lower()):
            score = 0
        elif short.startswith(needle) or title.startswith(needle):
            score = 1
        elif needle in title:
            score = 2
        elif all(w in title for w in words):
            score = 3
        else:
            score = 4
        scored.append((score, i, entry))
    return [e for _s, _i, e in sorted(scored, key=lambda x: (x[0], x[1]))][:limit]


def page(id: str, lang: Optional[str] = None) -> Page:  # noqa: A002
    """The page with ``id`` (``KeyError`` when there is none)."""
    lang = _language(lang)
    for provider in _all_providers():
        found = provider.page(id, lang)
        if found is not None:
            return found
    raise KeyError(f"no reference page {id!r}")


def lookup(symbol: str) -> Optional[str]:
    """The id of the page about a name written in code (``"pz.text"``, ``"ui.button"``, ``"Theme"``...)."""
    providers = _all_providers()
    for provider in [*providers[1:-1], providers[0], providers[-1]]:
        found = provider.lookup(symbol) if provider.lookup else None
        if found is not None:
            return found
    return None


class Browser:
    """What a reference viewer shows: the search text, the page open and the back/forward history.

    ``ui.reference_browser(browser)`` draws it; its buttons and links call the methods below.
    """

    def __init__(self, start: Optional[str] = None, *, lang: Optional[str] = None) -> None:
        self.lang = lang
        self.query = ""
        self.current: Optional[str] = start
        self.past: List[str] = []
        self.future: List[str] = []
        #: Sections unfolded in the class list (the one of the page shown opens by itself).
        self.expanded: set = set()
        #: Bumped when the page changes, so the view can scroll back to the top.
        self.revision = 0
        if start is not None:
            try:
                self.expanded.add(page(start, lang).entry.section)
            except KeyError:
                pass

    def open(self, id: str) -> bool:  # noqa: A002
        """Shows the page ``id`` (returns ``False`` when there is no such page)."""
        try:
            found = page(id, self.lang)
        except KeyError:
            return False
        self.expanded.add(found.entry.section)
        if id != self.current:
            if self.current is not None:
                self.past.append(self.current)
            self.future.clear()
            self.current = id
            self.revision += 1
        return True

    def open_symbol(self, symbol: str) -> bool:
        """Shows the page about a name written in code; returns whether one was found."""
        found = lookup(symbol)
        return self.open(found) if found else False

    def back(self) -> None:
        """Goes to the previous page."""
        if self.past:
            if self.current is not None:
                self.future.append(self.current)
            self.current = self.past.pop()
            self.revision += 1

    def forward(self) -> None:
        """Goes to the next page after going back."""
        if self.future:
            if self.current is not None:
                self.past.append(self.current)
            self.current = self.future.pop()
            self.revision += 1

    def set_query(self, query: str) -> None:
        """Changes the search text."""
        self.query = query

    def toggle(self, section: str) -> None:
        """Folds or unfolds a section of the class list."""
        self.expanded ^= {section}

    def results(self) -> List[Entry]:
        """The entries matching the search text."""
        return search(self.query, self.lang)

    def page(self) -> Optional[Page]:
        """The page shown (``None`` before one is opened)."""
        if self.current is None:
            return None
        try:
            return page(self.current, self.lang)
        except KeyError:
            return None

    def follow(self, url: str) -> Optional[str]:
        """Handles a link of a page: internal links open their page; returns the URL to open otherwise."""
        if url.startswith(LINK):
            self.open(url[len(LINK):])
            return None
        return internal_target(url) if url.startswith("/") else url
