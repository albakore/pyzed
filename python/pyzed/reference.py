"""A searchable reference of Pyzed, like Godot's built-in class reference.

Every widget, component, class and function of the library has a page with its signature,
description, parameters and members, and so does every control of the visual designer::

    from pyzed import reference

    reference.search("button")            # [Entry(id="pyzed.button", ...), Entry(id="pyzed.ui.button", ...), ...]
    page = reference.page("pyzed.ui.button")
    page.title, page.body                 # "ui.button", the page in Markdown
    reference.lookup("ui.button")         # "pyzed.ui.button"

Signatures, members and docstrings are read from the installed package when a page is built,
so they always match the code. The descriptions of the API reference (the same ones as the
website, in English and Spanish) ship with the package in ``pyzed/_reference/<lang>.json``,
generated by ``docs/scripts/gen_api.py``; a name without one falls back to its docstring.

``Browser`` keeps what a reference viewer needs (the search text, the page shown and the
history) and ``ui.reference_browser`` draws it, so any app can embed the same reference
the designer shows.
"""

from __future__ import annotations

import dataclasses
import importlib
import inspect
import json
import re
from dataclasses import dataclass
from functools import lru_cache
from pathlib import Path
from typing import Any, Callable, Dict, List, Optional, Tuple

from . import i18n

__all__ = [
    "Browser", "Entry", "Page", "Provider", "SITE", "entries", "languages", "lookup", "page", "register",
    "search", "sections",
]

DATA = Path(__file__).resolve().parent / "_reference"
SITE = "https://albakore.github.io/pyzed/"
#: Internal links in page bodies: ``[text](ref:pyzed.ui.button)``.
LINK = "ref:"

#: The icon of each reference page of the website, by slug.
PAGE_ICONS = {"app": "app-window", "command": "terminal", "widgets": "box", "ui": "component", "theme": "palette",
              "icons": "smile", "draw": "pen-tool", "designer": "layout-template"}


# -- data ---------------------------------------------------------------------------------------------


@dataclass(frozen=True)
class Entry:
    """One page of the reference, as search results and the class list show it."""

    id: str
    title: str
    #: The top level of the class list ("Core widgets", "Form controls"...).
    section: str
    #: The heading inside the section ("Layout", "Inputs"...).
    group: str = ""
    summary: str = ""
    icon: str = "book-open"
    #: "class", "function", "constant", "module", "control", "component" or "page".
    kind: str = "function"


@dataclass(frozen=True)
class Page:
    """A full page: the entry it belongs to and its body in Markdown."""

    entry: Entry
    body: str
    #: Where the same page lives on the website (``None`` when it has none).
    url: Optional[str] = None

    @property
    def id(self) -> str:
        """The entry's id."""
        return self.entry.id

    @property
    def title(self) -> str:
        """The entry's title."""
        return self.entry.title


@dataclass(frozen=True)
class Provider:
    """A section of the reference that comes from somewhere else than the library's API pages.

    ``entries(lang)`` lists its pages, ``page(id, lang)`` builds one (``None`` when the id is not
    its own) and ``lookup(symbol)`` turns a name written in code into one of its ids.
    """

    name: str
    entries: Callable[[str], List[Entry]]
    page: Callable[[str, str], Optional[Page]]
    lookup: Optional[Callable[[str], Optional[str]]] = None


_providers: List[Provider] = []
#: Modules that register a provider when they are imported (the designer's controls...).
_LAZY_PROVIDERS = ("pyzed.designer.help",)


def register(provider: Provider) -> Provider:
    """Adds a section to the reference (it replaces one with the same ``name``)."""
    _providers[:] = [p for p in _providers if p.name != provider.name]
    _providers.append(provider)
    return provider


def _all_providers() -> List[Provider]:
    for module in _LAZY_PROVIDERS:
        try:
            importlib.import_module(module)
        except ImportError:  # pragma: no cover - a partial install
            pass
    return [_LIBRARY, *_providers, _COMPONENTS]


def languages() -> List[str]:
    """The languages the API descriptions are available in."""
    return sorted(p.stem for p in DATA.glob("*.json"))


def _language(lang: Optional[str]) -> str:
    """``lang`` (the current language by default) reduced to one with data, falling back to English."""
    code = i18n.normalize(lang or i18n.language())
    for candidate in (code, code.split("_")[0]):
        if (DATA / f"{candidate}.json").is_file():
            return candidate
    return "en"


@lru_cache(maxsize=None)
def _data(lang: str) -> Dict[str, Any]:
    path = DATA / f"{lang}.json"
    if not path.is_file():
        return {"pages": [], "common": {}, "members": {}}
    return json.loads(path.read_text(encoding="utf-8"))


def _text(key: str, lang: str, **values: Any) -> str:
    return i18n.t(f"pyzed.reference.{key}", language=lang, **values)


# -- rendering helpers (shared with docs/scripts/gen_api.py) ------------------------------------------


def resolve(path: str) -> Any:
    """The object named by a dotted path such as ``"pyzed.ui.button"`` (importing submodules as needed)."""
    import pyzed

    obj: Any = pyzed
    parts = path.split(".")
    for i, part in enumerate(parts[1:], start=2):
        if not hasattr(obj, part):  # a submodule that isn't imported yet (pyzed.designer...)
            importlib.import_module(".".join(parts[:i]))
        obj = getattr(obj, part)
    return obj


def signature(name: str, obj: Any) -> str:
    """The signature of ``obj`` as the reference shows it (one line, or one parameter per line when long)."""
    short = name.rsplit(".", 1)[-1]
    if inspect.isclass(obj) and dataclasses.is_dataclass(obj):
        fields = []
        for f in dataclasses.fields(obj):
            if f.default is not dataclasses.MISSING:
                fields.append(f"{f.name}={f.default!r}")
            elif f.default_factory is not dataclasses.MISSING:  # type: ignore[misc]
                factory = f.default_factory  # type: ignore[misc]
                if factory in (list, dict, set, tuple):
                    fields.append(f"{f.name}={factory()!r}")
                else:
                    fields.append(f"{f.name}={factory.__module__}.{factory.__qualname__}()")
            else:
                fields.append(f.name)
        return f"@dataclass\nclass {short}({', '.join(fields)})"
    if inspect.isclass(obj):
        return f"class {short}"
    try:
        sig = obj if isinstance(obj, inspect.Signature) else inspect.signature(obj)
    except (TypeError, ValueError):
        return f"{short}(...)"
    params = []
    for p in sig.parameters.values():
        text = str(p.replace(annotation=inspect.Parameter.empty))
        params.append(text)
    # Rebuild the keyword-only "*" marker from the signature.
    rendered, seen_star = [], False
    for p, text in zip(sig.parameters.values(), params):
        if p.kind is inspect.Parameter.KEYWORD_ONLY and not seen_star:
            rendered.append("*")
            seen_star = True
        if p.kind is inspect.Parameter.VAR_POSITIONAL:
            seen_star = True
        rendered.append(text)
    one_line = f"{short}({', '.join(rendered)})"
    if len(one_line) <= 88:
        return one_line
    return f"{short}(\n" + "".join(f"    {r},\n" for r in rendered) + ")"


def param_names(obj: Any) -> List[str]:
    """The parameter names of a function or dataclass (without ``self`` and ``cls``)."""
    if inspect.isclass(obj) and dataclasses.is_dataclass(obj):
        return [f.name for f in dataclasses.fields(obj)]
    try:
        return [p for p in inspect.signature(obj).parameters if p not in ("self", "cls")]
    except (TypeError, ValueError):
        return []


def rst_to_md(text: str) -> str:
    """Docstrings use reST ``literals`` and ``::`` blocks; the reference uses Markdown."""
    out, lines, i = [], text.split("\n"), 0
    while i < len(lines):
        line = lines[i]
        if line.rstrip().endswith("::") and i + 1 < len(lines):
            out.append(line.rstrip()[:-1] if not line.rstrip().endswith(" ::") else line.rstrip()[:-3])
            block, i = [], i + 1
            while i < len(lines) and (not lines[i].strip() or lines[i].startswith(" ")):
                block.append(lines[i])
                i += 1
            while block and not block[-1].strip():
                block.pop()
            code = inspect.cleandoc("\n".join(block))
            out += ["", "```python", code, "```", ""]
            continue
        if line.strip() == "Events:" and i + 1 < len(lines) and lines[i + 1].startswith(" "):
            # ``on_x(args)``: text, one per line (deeper lines continue it) -> a list.
            out += [line.strip(), ""]
            indent, i = len(lines[i + 1]) - len(lines[i + 1].lstrip()), i + 1
            while i < len(lines) and lines[i].startswith(" "):
                if len(lines[i]) - len(lines[i].lstrip()) > indent and out[-1].startswith("- "):
                    out[-1] += " " + lines[i].strip()
                else:
                    out.append("- " + lines[i].strip())
                i += 1
            continue
        out.append(line)
        i += 1
    return re.sub(r"(?<!`)``([^`\n]+)``(?!`)", r"`\1`", "\n".join(out)).strip()


def first_paragraph(doc: Optional[str]) -> str:
    """The first paragraph of a docstring, on one line, in Markdown."""
    if not doc:
        return ""
    return rst_to_md(inspect.cleandoc(doc).split("\n\n")[0].replace("\n", " "))


def full_doc(obj: Any) -> str:
    """The whole docstring of ``obj`` in Markdown."""
    doc = inspect.getdoc(obj)
    return rst_to_md(doc) if doc else ""


def class_members(cls: type) -> List[Tuple[str, Any, str]]:
    """Public methods and properties a class defines itself, as ``(name, raw, "method" | "property")``.

    Inherited ones, and overrides of a parent's method (``Component.render``...), belong to the parent.
    """
    members = []
    for m, raw in vars(cls).items():
        if m.startswith("_") or any(m in vars(base) for base in cls.__mro__[1:]):
            continue
        if isinstance(raw, property):
            members.append((m, raw, "property"))
        elif isinstance(raw, (classmethod, staticmethod)) or inspect.isfunction(raw):
            members.append((m, raw, "method"))
    return members


def member_signature(cls: type, m: str, raw: Any, kind: str) -> str:
    """The signature of the member ``m`` of ``cls`` (properties are marked with a comment)."""
    if kind == "property":
        return f"{cls.__name__}.{m}  # property"
    func = getattr(cls, m)
    try:
        sig = inspect.signature(func)
    except (TypeError, ValueError):
        return f"{cls.__name__}.{m}(...)"
    params = list(sig.parameters.values())
    if inspect.isfunction(raw) and params and params[0].name in ("self", "cls"):
        params = params[1:]
    prefix = ("@classmethod\n" if isinstance(raw, classmethod)
              else "@staticmethod\n" if isinstance(raw, staticmethod) else "")
    text = signature(f"x.{cls.__name__}.{m}", sig.replace(parameters=params))
    return prefix + f"{cls.__name__}.{text}"


def member_doc(raw: Any, kind: str) -> str:
    """The first paragraph of a member's docstring."""
    func = raw.fget if kind == "property" else getattr(raw, "__func__", raw)
    return first_paragraph(getattr(func, "__doc__", None))


def display_name(name: str) -> str:
    """``"pyzed.text"`` -> ``"pz.text"``, ``"pyzed.ui.button"`` -> ``"ui.button"``."""
    if not name.startswith("pyzed."):
        return name
    rest = name[len("pyzed."):]
    head = rest.split(".", 1)[0]
    return f"pz.{rest}" if "." not in rest or head[:1].isupper() else rest


def summary(markdown: str) -> str:
    """The first sentence of a Markdown text, without formatting (for lists and search results)."""
    text = inspect.cleandoc(markdown or "").split("\n\n", 1)[0].replace("\n", " ")
    text = re.sub(r"\[([^\]]+)\]\([^)]*\)", r"\1", text)
    text = re.sub(r"[`*_]", "", text).strip()
    match = re.match(r"(.+?[.!?])(\s|$)", text)
    return (match.group(1) if match else text)[:200]


def tables_as_lists(markdown: str) -> str:
    """Markdown tables turned into bullet lists (``- first cell: the other cells``).

    For viewers whose tables don't wrap long cells, such as ``ui.reference_browser`` in a narrow tab.
    Code blocks are left alone.
    """
    out: List[str] = []
    lines = markdown.split("\n")
    i, fenced = 0, False
    while i < len(lines):
        line = lines[i]
        if line.lstrip().startswith("```"):
            fenced = not fenced
        is_table = (not fenced and line.lstrip().startswith("|") and i + 1 < len(lines)
                    and re.match(r"^\s*\|?\s*:?-{3,}", lines[i + 1]))
        if not is_table:
            out.append(line)
            i += 1
            continue
        i += 2
        while i < len(lines) and lines[i].lstrip().startswith("|"):
            cells = [c.strip() for c in re.split(r"(?<!\\)\|", lines[i].strip().strip("|"))]
            cells = [c.replace("\\|", "|") for c in cells]
            head, rest = cells[0], [c for c in cells[1:] if c and c != "—"]
            out.append(f"- {head}: {' · '.join(rest)}" if rest else f"- {head}")
            i += 1
    return "\n".join(out)


# -- the library's API pages --------------------------------------------------------------------------


def _kind_of(obj: Any) -> str:
    if inspect.isclass(obj):
        return "class"
    if inspect.ismodule(obj):
        return "module"
    if callable(obj):
        return "function"
    return "constant"


_KIND_ICONS = {"class": "box", "function": "square-function", "constant": "hash", "module": "package"}


def _anchor(name: str) -> str:
    return re.sub(r"[^a-z0-9_-]", "", name.rsplit(".", 1)[-1].lower().replace("_", "_"))


@lru_cache(maxsize=None)
def _library_index(lang: str) -> Tuple[Tuple[Entry, ...], Dict[str, Tuple[Dict[str, Any], str, str]]]:
    """The library's entries and, by id, ``(entry data, page slug, section)``."""
    data = _data(lang)
    entries: List[Entry] = []
    where: Dict[str, Tuple[Dict[str, Any], str, str]] = {}
    for page_data in data["pages"]:
        slug, title = page_data["slug"], page_data["title"]
        entries.append(Entry(id=f"page:{slug}", title=title, section=title, group="",
                             summary=summary(page_data.get("description", "")),
                             icon=PAGE_ICONS.get(slug, "book-open"), kind="page"))
        for section, items in page_data["sections"]:
            for name, item in items.items():
                try:
                    obj = resolve(name)
                except (AttributeError, ImportError):
                    continue
                text = item.get("desc") or (first_paragraph(getattr(obj, "__doc__", None)) if not
                                            inspect.ismodule(obj) else "")
                kind = _kind_of(obj)
                entries.append(Entry(id=name, title=display_name(name), section=title, group=section,
                                     summary=summary(text), icon=_KIND_ICONS.get(kind, "book-open"), kind=kind))
                where[name] = (item, slug, section)
    return tuple(entries), where


def _library_entries(lang: str) -> List[Entry]:
    return list(_library_index(lang)[0])


def _library_page(id: str, lang: str) -> Optional[Page]:  # noqa: A002 - mirrors Page.id
    entries, where = _library_index(lang)
    if id.startswith("page:"):
        return _overview_page(id[5:], lang)
    if id not in where:
        return None
    item, slug, section = where[id]
    entry = next(e for e in entries if e.id == id)
    return Page(entry=entry, body=entry_markdown(id, item, lang),
                url=f"{SITE}{'' if lang == 'en' else lang + '/'}reference/{slug}/#{_anchor(id)}")


def entry_markdown(name: str, item: Dict[str, Any], lang: str = "en") -> str:
    """The body of one API entry: signature, description, parameters, example and members.

    The same blocks as the website's reference (``docs/scripts/gen_api.py``), built from the live
    object, so signatures and members are always current.
    """
    data = _data(_language(lang))
    obj = resolve(name)
    out: List[str] = []
    if not item.get("no_signature"):
        out.append(f"```python\n{signature(name, obj)}\n```")
    description = item.get("desc") or (full_doc(obj) if item.get("docstring") else first_paragraph(
        getattr(obj, "__doc__", None)))
    if description:
        out.append(inspect.cleandoc(description))
    params = item.get("params", {})
    common = data.get("common", {})
    skip_params = item.get("no_signature") and not params or item.get("docstring")
    rows = []
    for p in ([] if skip_params else param_names(obj)):
        if p.startswith("*"):
            continue
        text = params.get(p) or common.get(p)
        if text:
            rows.append(f"| `{p}` | {_one_line(text)} |")
    if rows:
        out.append(f"| {_text('parameter', lang)} | {_text('description', lang)} |\n| --- | --- |\n"
                   + "\n".join(rows))
    if item.get("example"):
        out.append(f"```python\n{inspect.cleandoc(item['example'])}\n```")
    if item.get("extra"):
        out.append(inspect.cleandoc(item["extra"]))
    if inspect.isclass(obj) and item.get("members", True):
        members = _members_markdown(name, obj, item, data, lang)
        if members:
            out.append(members)
    return _localize_links("\n\n".join(out), lang)


def _one_line(text: str) -> str:
    return " ".join(inspect.cleandoc(text).split("\n"))


def _members_markdown(name: str, cls: type, item: Dict[str, Any], data: Dict[str, Any], lang: str) -> str:
    own = data.get("members", {})
    _entries, where = _library_index(_language(lang))
    skip = set(item.get("skip_members", ()))
    out = []
    for m, raw, kind in class_members(cls):
        full = f"{name}.{m}"
        if m in skip:
            continue
        if full in where:  # documented as an entry of its own
            out.append(f"#### [`{cls.__name__}.{m}`]({LINK}{full})")
            continue
        text = own.get(full) or member_doc(raw, kind)
        out.append(f"#### `{cls.__name__}.{m}`\n\n```python\n{member_signature(cls, m, raw, kind)}\n```\n\n{text}")
    if not out:
        return ""
    return f"## {_text('members', lang)}\n\n" + "\n\n".join(out)


def _overview_page(slug: str, lang: str) -> Optional[Page]:
    data = _data(lang)
    page_data = next((p for p in data["pages"] if p["slug"] == slug), None)
    if page_data is None:
        return None
    entries, _where = _library_index(lang)
    entry = next(e for e in entries if e.id == f"page:{slug}")
    out = [inspect.cleandoc(page_data.get("intro", ""))]
    for section, items in page_data["sections"]:
        rows = [f"- [`{display_name(n)}`]({LINK}{n}) {e.summary}" for n in items
                for e in entries if e.id == n]
        if rows:
            out.append(f"## {section}\n\n" + "\n".join(rows))
    return Page(entry=entry, body=_localize_links("\n\n".join(o for o in out if o), lang),
                url=f"{SITE}{'' if lang == 'en' else lang + '/'}reference/{slug}/")


def _localize_links(markdown: str, lang: str) -> str:
    """Links to the website's reference become internal links when the target has a page here."""
    _entries, where = _library_index(lang)
    by_anchor: Dict[Tuple[str, str], str] = {}
    for name, (_item, slug, _section) in where.items():
        by_anchor.setdefault((slug, _anchor(name)), name)

    def repl(match: "re.Match[str]") -> str:
        text, url = match.group(1), match.group(2)
        target = internal_target(url, by_anchor)
        return f"[{text}]({target})"

    return re.sub(r"\[([^\]]+)\]\(([^)\s]+)\)", repl, markdown)


def internal_target(url: str, by_anchor: Optional[Dict[Tuple[str, str], str]] = None) -> str:
    """``/pyzed/reference/widgets/#canvas`` -> ``ref:pyzed.canvas``; other site paths become full URLs."""
    if url.startswith((LINK, "http://", "https://", "mailto:", "#")):
        return url
    match = re.match(r"^/pyzed/(?:[a-z]{2}/)?reference/([a-z_-]+)/?(?:#(.+))?$", url)
    if match:
        slug, anchor = match.group(1), (match.group(2) or "")
        if by_anchor is not None and anchor and (slug, anchor) in by_anchor:
            return f"{LINK}{by_anchor[(slug, anchor)]}"
        if not anchor:
            return f"{LINK}page:{slug}"
    if url.startswith("/pyzed/"):
        return SITE + url[len("/pyzed/"):]
    return url


def _library_lookup(symbol: str) -> Optional[str]:
    import pyzed

    bare = symbol.strip().rstrip("()")
    if not bare:
        return None
    _entries, where = _library_index(_language(None))
    candidates = [bare]
    if bare.startswith("pz."):
        candidates = [f"pyzed.{bare[3:]}"]
    elif not bare.startswith("pyzed."):
        candidates = [f"pyzed.{bare}", f"pyzed.ui.{bare}"] if "." not in bare else [f"pyzed.{bare}"]
    for name in candidates:
        if name in where:
            return name
        # a member documented on its class page: pyzed.Theme.derive -> pyzed.Theme
        parent = name.rsplit(".", 1)[0]
        if parent in where and parent != "pyzed" and hasattr(_safe_resolve(parent), name.rsplit(".", 1)[1]):
            return parent
    if "." not in bare and hasattr(pyzed, bare) and f"pyzed.{bare}" in where:
        return f"pyzed.{bare}"
    return None


def _safe_resolve(name: str) -> Any:
    try:
        return resolve(name)
    except (AttributeError, ImportError):
        return None


_LIBRARY = Provider("library", _library_entries, _library_page, _library_lookup)


# -- components defined in the app --------------------------------------------------------------------


def _user_classes() -> List[type]:
    from .component import registered

    return [cls for cls in registered() if not cls.__module__.startswith("pyzed.")]


def _component_entries(lang: str) -> List[Entry]:
    return [Entry(id=f"component:{cls.__name__}", title=cls.__name__, section=_text("your_components", lang),
                  group=getattr(cls, "category", "") or "", summary=summary(cls.describe() or ""),
                  icon=getattr(cls, "icon", None) or "component", kind="component")
            for cls in _user_classes()]


def _component_page(id: str, lang: str) -> Optional[Page]:  # noqa: A002
    if not id.startswith("component:"):
        return None
    cls = next((c for c in _user_classes() if c.__name__ == id.split(":", 1)[1]), None)
    if cls is None:
        return None
    entry = next(e for e in _component_entries(lang) if e.id == id)
    return Page(entry=entry, body=component_markdown(cls, lang))


def component_markdown(cls: type, lang: Optional[str] = None) -> str:
    """The page of a ``pz.Component`` subclass: its docstring, props, state, events and methods."""
    lang = _language(lang)
    out = [f"```python\n{cls.__name__}({', '.join(cls.__props__)})\n```" if getattr(cls, "__props__", None)
           else f"```python\nclass {cls.__name__}(pz.Component)\n```"]
    doc = full_doc(cls)
    if doc:
        out.append(doc)
    props = getattr(cls, "__props__", {})
    if props:
        rows = [f"| `{p.name}` | `{_annotation(p.annotation)}` | "
                f"{'—' if p.required else f'`{p.default!r}`'} | {getattr(p, 'doc', '') or ''} |"
                for p in props.values()]
        out.append(f"## {_text('props', lang)}\n\n| {_text('name', lang)} | {_text('type', lang)} | "
                   f"{_text('default', lang)} | {_text('description', lang)} |\n| --- | --- | --- | --- |\n"
                   + "\n".join(rows))
    state = getattr(cls, "__state__", {})
    if state:
        rows = [f"| `{s.name}` | `{_annotation(s.annotation)}` | `{s.default!r}` | {s.doc or ''} |"
                for s in state.values()]
        out.append(f"## {_text('state', lang)}\n\n| {_text('name', lang)} | {_text('type', lang)} | "
                   f"{_text('default', lang)} | {_text('description', lang)} |\n| --- | --- | --- | --- |\n"
                   + "\n".join(rows))
    events = getattr(cls, "__events__", {})
    if events:
        out.append(f"## {_text('events', lang)}\n\n| {_text('name', lang)} | {_text('description', lang)} |\n"
                   "| --- | --- |\n" + "\n".join(f"| `{n}` | {d or ''} |" for n, d in events.items()))
    methods = [(m, raw, kind) for m, raw, kind in class_members(cls)
               if kind == "method" and m not in ("render",)]
    if methods:
        out.append(f"## {_text('methods', lang)}\n\n" + "\n\n".join(
            f"#### `{m}`\n\n```python\n{member_signature(cls, m, raw, kind)}\n```\n\n{member_doc(raw, kind)}"
            for m, raw, kind in methods))
    return "\n\n".join(out)


def _annotation(annotation: Any) -> str:
    if isinstance(annotation, str):
        return annotation
    return getattr(annotation, "__name__", None) or str(annotation).replace("typing.", "")


def _component_lookup(symbol: str) -> Optional[str]:
    bare = symbol.strip().rstrip("()").split(".")[-1]
    return f"component:{bare}" if any(c.__name__ == bare for c in _user_classes()) else None


