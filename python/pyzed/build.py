"""``pyzed build``: package a Pyzed project as a standalone app with PyInstaller.

PyInstaller freezes the project's ``.venv`` (Python, ``pyzed-ui`` and every dependency)
next to a small launcher that opens the main form. Builds are native: run it on
Windows for a ``.exe``, on macOS for a ``.app`` and on Linux for an ELF executable (a CI
matrix builds all three; see ``workflow()``).

Form handlers are loaded from their ``.py`` files at runtime, so PyInstaller cannot see
what they import. This module reads them with ``ast`` and passes every imported
module as a hidden import, ships the UI folder as data and adds ``ui/``, ``src/`` and the
project root to the search path, so code outside the UI folder is bundled too.

Settings come from ``[tool.pyzed.build]`` in ``pyproject.toml``::

    [tool.pyzed.build]
    name = "My App"               # executable / bundle name (default: the project name)
    onefile = false               # one self-extracting file instead of a folder
    windowed = true               # no console window (Windows, macOS)
    icon = "assets/icon.ico"      # .ico on Windows, .icns on macOS
    include = ["assets", "data/config.toml"]   # extra files and folders to ship
    hidden-imports = ["mypkg.plugins.csv"]     # modules imported dynamically
    collect = ["mypkg"]           # packages to ship whole (code, data and binaries)
    args = ["--noupx"]            # anything else, passed to PyInstaller as is
"""

from __future__ import annotations

import ast
import os
import sys
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Dict, List, Optional, Sequence, Set

from .project import Project, Result, _uv, execute, iter_python_files, module_name

PYINSTALLER = "pyinstaller>=6.10"

LAUNCHER = '''"""Generated by `pyzed build`: opens {name} from the bundled UI folder."""

import sys
from pathlib import Path

if hasattr(sys, "_MEIPASS"):  # PyInstaller
    ROOT = Path(sys._MEIPASS)
elif "__compiled__" in globals():  # Nuitka
    ROOT = Path(__file__).resolve().parent
else:  # not packaged: the project itself
    ROOT = Path(r"{root}")
UI = ROOT / {ui!r}
# Handlers may import helper modules that live next to them, at any time.
sys.path.insert(0, str(UI))

from pyzed import designer  # noqa: E402

designer.run(ROOT / {main!r})
'''

WORKFLOW = """\
name: Build

# Builds the app on each platform with `pyzed build` and keeps the result as an
# artifact (Actions -> this run -> Artifacts). PyInstaller cannot cross-compile, so
# every platform builds on its own runner.
on:
  push:
    tags: ["v*"]
  workflow_dispatch:

jobs:
  build:
    name: Build ${{ matrix.os }}
    runs-on: ${{ matrix.os }}
    strategy:
      fail-fast: false
      matrix:
        os: [ubuntu-latest, windows-latest, macos-latest]
    steps:
      - uses: actions/checkout@v4
      - uses: astral-sh/setup-uv@v6
      - run: uv sync --locked
      - run: uv run pyzed build
      - uses: actions/upload-artifact@v4
        with:
          name: {name}-${{ runner.os }}
          path: dist/
"""


@dataclass
class BuildOptions:
    """What ``pyzed build`` packages and how (defaults come from ``[tool.pyzed.build]``)."""

    name: Optional[str] = None
    onefile: bool = False
    windowed: bool = True
    icon: Optional[str] = None
    include: List[str] = field(default_factory=list)
    hidden_imports: List[str] = field(default_factory=list)
    collect: List[str] = field(default_factory=list)
    args: List[str] = field(default_factory=list)
    clean: bool = True

    @classmethod
    def from_project(cls, project: Project, **overrides: Any) -> "BuildOptions":
        table: Dict[str, Any] = dict(project.config.get("build", {}))
        opts = cls(
            name=table.get("name"),
            onefile=bool(table.get("onefile", False)),
            windowed=bool(table.get("windowed", True)),
            icon=table.get("icon"),
            include=list(table.get("include", [])),
            hidden_imports=list(table.get("hidden-imports", [])),
            collect=list(table.get("collect", [])),
            args=list(table.get("args", [])),
        )
        for key, value in overrides.items():
            if value is not None:
                setattr(opts, key, value)
        return opts


def imported_modules(folder: Path) -> Set[str]:
    """Modules imported by the ``.py`` files under ``folder`` (not counting the files themselves)."""
    local = {p.stem for p in iter_python_files(folder)} if folder.is_dir() else set()
    found: Set[str] = set()
    for path in iter_python_files(folder) if folder.is_dir() else ():
        try:
            tree = ast.parse(path.read_text(encoding="utf-8"), str(path))
        except (SyntaxError, UnicodeDecodeError):
            continue
        for node in ast.walk(tree):
            if isinstance(node, ast.Import):
                found.update(alias.name for alias in node.names)
            elif isinstance(node, ast.ImportFrom) and node.module and node.level == 0:
                found.add(node.module)
    return {m for m in found if m.split(".")[0] not in local and m != "__future__"}


def _data(source: Path, dest: str) -> str:
    return f"{source}{os.pathsep}{dest}"


def launcher(project: Project, folder: Path) -> Path:
    """Writes the entry script PyInstaller starts from; returns its path."""
    folder.mkdir(parents=True, exist_ok=True)
    path = folder / f"{module_name(project.name)}_launcher.py"
    text = LAUNCHER.format(name=project.name, root=project.root,
                           ui=project.ui_dir.relative_to(project.root).as_posix(),
                           main=project.main_form.relative_to(project.root).as_posix())
    path.write_text(text, encoding="utf-8")
    return path


def pyinstaller_args(project: Project, opts: BuildOptions) -> List[str]:
    """The PyInstaller command line for ``project`` (without the ``pyinstaller`` itself)."""
    work = project.root / "build" / "pyzed"
    entry = launcher(project, work)
    root = project.root
    args: List[str] = [str(entry), "--name", opts.name or project.name, "--noconfirm",
                       "--distpath", str(root / "dist"), "--workpath", str(work), "--specpath", str(work)]
    if opts.clean:
        args.append("--clean")
    args.append("--onefile" if opts.onefile else "--onedir")
    if opts.windowed:
        args.append("--windowed")
    if opts.icon:
        args += ["--icon", str(root / opts.icon)]
    for folder in project.paths():
        args += ["--paths", str(folder)]
    ui_rel = project.ui_dir.relative_to(root).as_posix()
    args += ["--add-data", _data(project.ui_dir, ui_rel)]
    for item in opts.include:
        source = root / item
        dest = Path(item).as_posix() if source.is_dir() else (Path(item).parent.as_posix() or ".")
        args += ["--add-data", _data(source, dest)]
    # pyzed's themes and templates are data files; its designer is loaded by the launcher.
    args += ["--collect-data", "pyzed", "--collect-submodules", "pyzed"]
    own = module_name(project.name)
    if project.src_dir is not None and (project.src_dir / own).is_dir():
        args += ["--collect-submodules", own]
    for module in sorted(imported_modules(project.ui_dir) | set(opts.hidden_imports)):
        args += ["--hidden-import", module]
    for package in opts.collect:
        args += ["--collect-all", package]
    return args + list(opts.args)


def command(project: Project, opts: BuildOptions) -> List[str]:
    """``uv run --with pyinstaller pyinstaller ...``: PyInstaller runs inside the project's environment."""
    return [_uv(), "run", "--with", PYINSTALLER, "pyinstaller", *pyinstaller_args(project, opts)]


def output(project: Project, opts: BuildOptions) -> Path:
    """Where the app ends up (``dist/<name>/``, ``dist/<name>.exe``, ``dist/<name>.app``...)."""
    name = opts.name or project.name
    dist = project.root / "dist"
    if sys.platform == "darwin" and opts.windowed:
        return dist / f"{name}.app"
    if opts.onefile:
        return dist / (name + (".exe" if os.name == "nt" else ""))
    return dist / name


def build(project: Project, opts: Optional[BuildOptions] = None) -> Result:
    """Packages ``project`` for the current platform and returns PyInstaller's output."""
    opts = opts or BuildOptions.from_project(project)
    if not project.main_form.exists():
        return Result([], 1, f"{project.main_form} does not exist; set [tool.pyzed] main in pyproject.toml")
    return execute(command(project, opts), project.root)


def workflow(project: Project, path: Optional[Path] = None) -> Path:
    """Writes a GitHub Actions workflow that builds the app on Linux, Windows and macOS."""
    path = path or project.root / ".github" / "workflows" / "build.yml"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(WORKFLOW.replace("{name}", module_name(project.name)), encoding="utf-8")
    return path


def describe(args: Sequence[str]) -> str:
    """A copy-pasteable form of ``args``."""
    import shlex

    return " ".join(shlex.quote(a) for a in args)
