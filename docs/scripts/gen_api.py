"""Generates the API reference (docs/src/content/docs/[es/]reference/*.md) from the installed package.

    maturin develop --release
    python docs/scripts/gen_api.py              # writes the pages in every language
    python docs/scripts/gen_api.py --lang es    # only one language
    python docs/scripts/gen_api.py --check      # fails if a public name is undocumented

Signatures come from ``inspect`` (Rust functions too, PyO3 exposes them), so they always match the
code. Descriptions live in ``api_docs_<lang>.py`` (``api_docs_en.py`` for English, the site's main
language, ``api_docs_es.py`` for Spanish); a missing one falls back to the docstring and ``--check``
reports it.
"""

from __future__ import annotations

import argparse
import dataclasses
import importlib
import inspect
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
DOCS = HERE.parent / "src" / "content" / "docs"
sys.path.insert(0, str(HERE))

import pyzed  # noqa: E402

# Output folder and fixed strings per language. English is the site root.
LANGS = {
    "en": {"out": DOCS / "reference", "param": "Parameter", "desc": "Description",
           "generated": "Generated by docs/scripts/gen_api.py. Edit docs/scripts/api_docs_en.py."},
    "es": {"out": DOCS / "es" / "reference", "param": "Parámetro", "desc": "Descripción",
           "generated": "Archivo generado por docs/scripts/gen_api.py. Edita docs/scripts/api_docs_es.py."},
}


def resolve(path: str):
    obj = pyzed
    for part in path.split(".")[1:]:
        obj = getattr(obj, part)
    return obj


def signature(name: str, obj) -> str:
    short = name.rsplit(".", 1)[-1]
    if inspect.isclass(obj) and dataclasses.is_dataclass(obj):
        fields = []
        for f in dataclasses.fields(obj):
            if f.default is not dataclasses.MISSING:
                fields.append(f"{f.name}={f.default!r}")
            elif f.default_factory is not dataclasses.MISSING:  # type: ignore[misc]
                fields.append(f"{f.name}={f.default_factory()!r}")
            else:
                fields.append(f.name)
        return f"@dataclass\nclass {short}({', '.join(fields)})"
    if inspect.isclass(obj):
        return f"class {short}"
    try:
        sig = inspect.signature(obj)
    except (TypeError, ValueError):
        return f"{short}(...)"
    params = []
    for p in sig.parameters.values():
        text = str(p.replace(annotation=inspect.Parameter.empty))
        params.append(text)
    # Rebuild the keyword-only "*" marker from the signature.
    rendered, seen_star = [], False
    for p, text in zip(sig.parameters.values(), params):
        if p.kind is inspect.Parameter.KEYWORD_ONLY and not seen_star:
            rendered.append("*")
            seen_star = True
        if p.kind is inspect.Parameter.VAR_POSITIONAL:
            seen_star = True
        rendered.append(text)
    one_line = f"{short}({', '.join(rendered)})"
    if len(one_line) <= 88:
        return one_line
    return f"{short}(\n" + "".join(f"    {r},\n" for r in rendered) + ")"


def param_names(obj):
    if inspect.isclass(obj) and dataclasses.is_dataclass(obj):
        return [f.name for f in dataclasses.fields(obj)]
    try:
        return [p for p in inspect.signature(obj).parameters if p not in ("self", "cls")]
    except (TypeError, ValueError):
        return []


def first_paragraph(doc: str | None) -> str:
    if not doc:
        return ""
    return inspect.cleandoc(doc).split("\n\n")[0].replace("\n", " ")


def render_item(name: str, entry: dict, common: dict, labels: dict, missing: list) -> str:
    obj = resolve(name)
    short = name.rsplit(".", 1)[-1]
    out = [f"### `{short}`\n"]
    if not entry.get("no_signature"):
        out.append(f"```python\n{signature(name, obj)}\n```\n")
    description = entry.get("desc")
    if not description:
        description = first_paragraph(getattr(obj, "__doc__", None))
        missing.append(name)
    out.append(description.strip() + "\n")
    params = entry.get("params", {})
    rows = []
    for p in ([] if entry.get("no_signature") and not params else param_names(obj)):
        if p.startswith("*"):
            continue
        text = params.get(p) or common.get(p)
        if text is None:
            missing.append(f"{name}({p})")
            continue
        rows.append(f"| `{p}` | {text} |")
    if rows:
        out.append(f"| {labels['param']} | {labels['desc']} |\n| --- | --- |\n" + "\n".join(rows) + "\n")
    if entry.get("example"):
        out.append(f"```python\n{inspect.cleandoc(entry['example'])}\n```\n")
    if entry.get("extra"):
        out.append(inspect.cleandoc(entry["extra"]) + "\n")
    return "\n".join(out)


def undocumented_exports(documented: set) -> list:
    missing = []
    for module, prefix in ((pyzed, "pyzed"), (pyzed.ui, "pyzed.ui")):
        for export in getattr(module, "__all__", []):
            obj = getattr(module, export)
            if inspect.ismodule(obj) or export in ("theme", "icons", "ui"):
                continue
            if f"{prefix}.{export}" not in documented:
                missing.append(f"{prefix}.{export}")
    return missing


def build(lang: str) -> tuple[dict, list]:
    """Renders every reference page for ``lang``; returns ``({slug: markdown}, missing)``."""
    docs = importlib.import_module(f"api_docs_{lang}")
    labels = LANGS[lang]
    missing: list = []
    documented = set()
    pages = {}
    for page in docs.PAGES:
        body = [
            "---",
            f"title: {json.dumps(page['title'], ensure_ascii=False)}",
            f"description: {json.dumps(page['description'], ensure_ascii=False)}",
            "sidebar:",
            f"  order: {page['order']}",
            "---",
            "",
            f"<!-- {labels['generated']} -->",
            "",
            inspect.cleandoc(page.get("intro", "")),
            "",
        ]
        for section, items in page["sections"]:
            body.append(f"## {section}\n")
            for name, entry in items.items():
                documented.add(name)
                body.append(render_item(name, entry, docs.COMMON, labels, missing))
        pages[page["slug"]] = "\n".join(body).rstrip() + "\n"
    missing += undocumented_exports(documented)
    return pages, missing


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="only report undocumented names")
    parser.add_argument("--lang", choices=sorted(LANGS), help="only this language (default: all)")
    args = parser.parse_args()

    failed = False
    for lang in [args.lang] if args.lang else LANGS:
        pages, missing = build(lang)
        if args.check:
            for m in missing:
                print(f"[{lang}] undocumented: {m}")
            failed |= bool(missing)
            continue
        out = LANGS[lang]["out"]
        out.mkdir(parents=True, exist_ok=True)
        for slug, text in pages.items():
            (out / f"{slug}.md").write_text(text, encoding="utf-8")
        print(f"[{lang}] wrote {len(pages)} pages to {out}")
        for m in missing:
            print(f"[{lang}] warning: undocumented: {m}")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
