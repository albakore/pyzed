"""Generates the API reference (docs/src/content/docs/[es/]reference/*.md) from the installed package.

    maturin develop --release
    python docs/scripts/gen_api.py              # writes the pages in every language
    python docs/scripts/gen_api.py --lang es    # only one language
    python docs/scripts/gen_api.py --check      # fails if a public name is undocumented

Signatures come from ``inspect`` (Rust functions too, PyO3 exposes them), so they always match the
code. Descriptions live in ``api_docs_<lang>.py`` (``api_docs_en.py`` for English, the site's main
language, ``api_docs_es.py`` for Spanish); a missing one falls back to the docstring and ``--check``
reports it.
"""

from __future__ import annotations

import argparse
import dataclasses
import importlib
import inspect
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
DOCS = HERE.parent / "src" / "content" / "docs"
sys.path.insert(0, str(HERE))

import pyzed  # noqa: E402

# Output folder and fixed strings per language. English is the site root.
LANGS = {
    "en": {"lang": "en", "out": DOCS / "reference", "param": "Parameter", "desc": "Description",
           "members": "Methods and properties",
           "generated": "Generated by docs/scripts/gen_api.py. Edit docs/scripts/api_docs_en.py."},
    "es": {"lang": "es", "out": DOCS / "es" / "reference", "param": "Parámetro", "desc": "Descripción",
           "members": "Métodos y propiedades",
           "generated": "Archivo generado por docs/scripts/gen_api.py. Edita docs/scripts/api_docs_es.py."},
}


def resolve(path: str):
    obj = pyzed
    parts = path.split(".")
    for i, part in enumerate(parts[1:], start=2):
        if not hasattr(obj, part):  # a submodule that isn't imported yet (pyzed.designer...)
            importlib.import_module(".".join(parts[:i]))
        obj = getattr(obj, part)
    return obj


def signature(name: str, obj) -> str:
    short = name.rsplit(".", 1)[-1]
    if inspect.isclass(obj) and dataclasses.is_dataclass(obj):
        fields = []
        for f in dataclasses.fields(obj):
            if f.default is not dataclasses.MISSING:
                fields.append(f"{f.name}={f.default!r}")
            elif f.default_factory is not dataclasses.MISSING:  # type: ignore[misc]
                fields.append(f"{f.name}={f.default_factory()!r}")
            else:
                fields.append(f.name)
        return f"@dataclass\nclass {short}({', '.join(fields)})"
    if inspect.isclass(obj):
        return f"class {short}"
    try:
        sig = obj if isinstance(obj, inspect.Signature) else inspect.signature(obj)
    except (TypeError, ValueError):
        return f"{short}(...)"
    params = []
    for p in sig.parameters.values():
        text = str(p.replace(annotation=inspect.Parameter.empty))
        params.append(text)
    # Rebuild the keyword-only "*" marker from the signature.
    rendered, seen_star = [], False
    for p, text in zip(sig.parameters.values(), params):
        if p.kind is inspect.Parameter.KEYWORD_ONLY and not seen_star:
            rendered.append("*")
            seen_star = True
        if p.kind is inspect.Parameter.VAR_POSITIONAL:
            seen_star = True
        rendered.append(text)
    one_line = f"{short}({', '.join(rendered)})"
    if len(one_line) <= 88:
        return one_line
    return f"{short}(\n" + "".join(f"    {r},\n" for r in rendered) + ")"


def param_names(obj):
    if inspect.isclass(obj) and dataclasses.is_dataclass(obj):
        return [f.name for f in dataclasses.fields(obj)]
    try:
        return [p for p in inspect.signature(obj).parameters if p not in ("self", "cls")]
    except (TypeError, ValueError):
        return []


def first_paragraph(doc: str | None) -> str:
    if not doc:
        return ""
    return rst_to_md(inspect.cleandoc(doc).split("\n\n")[0].replace("\n", " "))


def rst_to_md(text: str) -> str:
    """Docstrings use reST ``literals`` and ``::`` blocks; the site uses Markdown."""
    out, lines, i = [], text.split("\n"), 0
    while i < len(lines):
        line = lines[i]
        if line.rstrip().endswith("::") and i + 1 < len(lines):
            out.append(line.rstrip()[:-1] if not line.rstrip().endswith(" ::") else line.rstrip()[:-3])
            block, i = [], i + 1
            while i < len(lines) and (not lines[i].strip() or lines[i].startswith(" ")):
                block.append(lines[i])
                i += 1
            while block and not block[-1].strip():
                block.pop()
            code = inspect.cleandoc("\n".join(block))
            out += ["", "```python", code, "```", ""]
            continue
        out.append(line)
        i += 1
    return re.sub(r"``([^`]+)``", r"`\1`", "\n".join(out)).strip()


def full_doc(obj) -> str:
    doc = inspect.getdoc(obj)
    return rst_to_md(doc) if doc else ""


def class_members(cls) -> list:
    """Public methods and properties a class defines itself. Inherited ones, and overrides of a
    parent's method (``Component.render``...), are documented on the parent."""
    members = []
    for m, raw in vars(cls).items():
        if m.startswith("_") or any(m in vars(base) for base in cls.__mro__[1:]):
            continue
        if isinstance(raw, property):
            members.append((m, raw, "property"))
        elif isinstance(raw, (classmethod, staticmethod)) or inspect.isfunction(raw):
            members.append((m, raw, "method"))
    return members


def member_signature(cls, m: str, raw, kind: str) -> str:
    if kind == "property":
        return f"{cls.__name__}.{m}  # property"
    func = getattr(cls, m)
    try:
        sig = inspect.signature(func)
    except (TypeError, ValueError):
        return f"{cls.__name__}.{m}(...)"
    params = list(sig.parameters.values())
    if inspect.isfunction(raw) and params and params[0].name in ("self", "cls"):
        params = params[1:]
    prefix = "@classmethod\n" if isinstance(raw, classmethod) else "@staticmethod\n" if isinstance(raw, staticmethod) else ""
    text = signature(f"x.{cls.__name__}.{m}", sig.replace(parameters=params))
    return prefix + f"{cls.__name__}.{text}"


def render_members(name: str, cls, entry: dict, docs, labels: dict, documented_all: set, missing: list) -> str:
    """The "Methods and properties" block of a class: one small heading per member."""
    own = docs.MEMBERS if hasattr(docs, "MEMBERS") else {}
    skip = set(entry.get("skip_members", ()))
    out = []
    for m, raw, kind in class_members(cls):
        full = f"{name}.{m}"
        if m in skip or full in documented_all:
            continue
        text = own.get(full)
        if not text:
            func = raw.fget if kind == "property" else getattr(raw, "__func__", raw)
            text = first_paragraph(getattr(func, "__doc__", None))
            if labels["lang"] != "en" or not text:
                missing.append(full)
        out.append(f"#### `{cls.__name__}.{m}`\n\n```python\n{member_signature(cls, m, raw, kind)}\n```\n\n{text}\n")
    if not out:
        return ""
    return f"**{labels['members']}**\n\n" + "\n".join(out)


def render_item(name: str, entry: dict, common: dict, labels: dict, missing: list, docs=None,
                documented_all: frozenset = frozenset()) -> str:
    obj = resolve(name)
    short = name.rsplit(".", 1)[-1]
    out = [f"### `{short}`\n"]
    if not entry.get("no_signature"):
        out.append(f"```python\n{signature(name, obj)}\n```\n")
    description = entry.get("desc")
    if not description:
        # English pages may take the docstring as is; any other language needs a translation.
        description = full_doc(obj) if entry.get("docstring") else first_paragraph(getattr(obj, "__doc__", None))
        if labels["lang"] != "en" or not entry.get("docstring") or not description:
            missing.append(name)
    out.append(description.strip() + "\n")
    params = entry.get("params", {})
    rows = []
    # With ``docstring`` the parameters are described in the text itself.
    skip_params = entry.get("no_signature") and not params or entry.get("docstring")
    for p in ([] if skip_params else param_names(obj)):
        if p.startswith("*"):
            continue
        text = params.get(p) or common.get(p)
        if text is None:
            missing.append(f"{name}({p})")
            continue
        rows.append(f"| `{p}` | {text} |")
    if rows:
        out.append(f"| {labels['param']} | {labels['desc']} |\n| --- | --- |\n" + "\n".join(rows) + "\n")
    if entry.get("example"):
        out.append(f"```python\n{inspect.cleandoc(entry['example'])}\n```\n")
    if entry.get("extra"):
        out.append(inspect.cleandoc(entry["extra"]) + "\n")
    if inspect.isclass(obj) and docs is not None and entry.get("members", True):
        block = render_members(name, obj, entry, docs, labels, documented_all, missing)
        if block:
            out.append(block)
    return "\n".join(out)


def undocumented_exports(documented: set) -> list:
    missing = []
    import pyzed.designer

    for module, prefix in ((pyzed, "pyzed"), (pyzed.ui, "pyzed.ui"), (pyzed.designer, "pyzed.designer")):
        for export in getattr(module, "__all__", []):
            obj = getattr(module, export)
            if inspect.ismodule(obj) or export in ("theme", "icons", "ui"):
                continue
            if f"{prefix}.{export}" not in documented:
                missing.append(f"{prefix}.{export}")
    return missing


def build(lang: str) -> tuple[dict, list]:
    """Renders every reference page for ``lang``; returns ``({slug: markdown}, missing)``."""
    docs = importlib.import_module(f"api_docs_{lang}")
    labels = LANGS[lang]
    missing: list = []
    documented = set()
    documented_all = frozenset(n for page in docs.PAGES for _, items in page["sections"] for n in items)
    pages = {}
    for page in docs.PAGES:
        body = [
            "---",
            f"title: {json.dumps(page['title'], ensure_ascii=False)}",
            f"description: {json.dumps(page['description'], ensure_ascii=False)}",
            "sidebar:",
            f"  order: {page['order']}",
            "---",
            "",
            f"<!-- {labels['generated']} -->",
            "",
            inspect.cleandoc(page.get("intro", "")),
            "",
        ]
        for section, items in page["sections"]:
            body.append(f"## {section}\n")
            for name, entry in items.items():
                documented.add(name)
                body.append(render_item(name, entry, docs.COMMON, labels, missing, docs, documented_all))
        pages[page["slug"]] = "\n".join(body).rstrip() + "\n"
    missing += undocumented_exports(documented)
    return pages, missing


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="only report undocumented names")
    parser.add_argument("--lang", choices=sorted(LANGS), help="only this language (default: all)")
    args = parser.parse_args()

    failed = False
    for lang in [args.lang] if args.lang else LANGS:
        pages, missing = build(lang)
        if args.check:
            for m in missing:
                print(f"[{lang}] undocumented: {m}")
            failed |= bool(missing)
            continue
        out = LANGS[lang]["out"]
        out.mkdir(parents=True, exist_ok=True)
        for slug, text in pages.items():
            (out / f"{slug}.md").write_text(text, encoding="utf-8")
        print(f"[{lang}] wrote {len(pages)} pages to {out}")
        for m in missing:
            print(f"[{lang}] warning: undocumented: {m}")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
