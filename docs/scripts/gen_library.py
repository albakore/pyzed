def text(value, lang: str):
    """A ``T(en, es)`` value (or a plain one, the same in every language) in ``lang``."""
    return value[lang] if isinstance(value, dict) and set(value) == {"en", "es"} else value


def name_of(entry: dict, lang: str) -> str:
    return text(entry["name"], lang)


_CODE_SPAN = re.compile(r"(`+)(.+?)\1", re.DOTALL)


def mdx(prose: str) -> str:
    """Escapes ``{``, ``}`` and ``<`` outside code spans so Markdown prose is valid MDX."""
    out, last = [], 0
    for m in _CODE_SPAN.finditer(prose):
        out.append(_escape(prose[last:m.start()]))
        out.append(m.group(0))
        last = m.end()
    out.append(_escape(prose[last:]))
    return "".join(out)


def _escape(chunk: str) -> str:
    chunk = chunk.replace("{", "\\{").replace("}", "\\}")
    return re.sub(r"<(?!/?kbd>)", "&lt;", chunk)


def localize_links(prose: str, lang: str) -> str:
    """English text links to ``/pyzed/...``; other languages to ``/pyzed/<lang>/...``."""
    if lang == "en":
        return prose
    return re.sub(r"\]\(/pyzed/(?!" + lang + r"/)", f"](/pyzed/{lang}/", prose)


def prose(value, lang: str) -> str:
    return mdx(localize_links(inspect.cleandoc(text(value, lang)), lang))


def sort_key(name: str) -> str:
    return unicodedata.normalize("NFKD", name.casefold()).encode("ascii", "ignore").decode()


def slugify(heading: str) -> str:
    """github-slugger, which Starlight uses for heading ids."""
    value = heading.strip().lower()
    value = re.sub(r"[^\w\- ]", "", value)
    return value.replace(" ", "-")


def heading_anchors(path: Path) -> dict:
    """``{"### `button`": "button", ...}`` for every heading of a generated reference page."""
    anchors, seen, fence = {}, {}, False
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.startswith("```"):
            fence = not fence
            continue
        m = None if fence else re.match(r"^(#{2,6}) (.+)$", line)
        if not m:
            continue
        base = slugify(re.sub(r"[`*_]", lambda c: "_" if c.group(0) == "_" else "", m.group(2)))
        n = seen.get(base, 0)
        seen[base] = n + 1
        anchors.setdefault(m.group(2).strip(), base if n == 0 else f"{base}-{n}")
    return anchors


class Api:
    """Where each public name is documented in the API reference of one language."""

    def __init__(self, lang: str):
        self.lang = lang
        self.docs = importlib.import_module(f"api_docs_{lang}")
        self.where: dict = {}
        ref = DOCS / ("reference" if lang == "en" else f"{lang}/reference")
        for page in self.docs.PAGES:
            anchors = heading_anchors(ref / f"{page['slug']}.md") if (ref / f"{page['slug']}.md").exists() else {}
            for _, items in page["sections"]:
                for name, entry in items.items():
                    short = name.rsplit(".", 1)[-1]
                    anchor = anchors.get(f"`{short}`")
                    self.where[name] = (page["slug"], anchor, entry)

    def link(self, name: str) -> str:
        slug, anchor, _ = self.where[name]
        prefix = LANGS[self.lang]["prefix"]
        return f"{prefix}/reference/{slug}/" + (f"#{anchor}" if anchor else "")


def short_name(name: str) -> str:
    """``pyzed.ui.button`` -> ``ui.button``; ``pyzed.row`` -> ``pz.row``."""
    if name.startswith("pyzed.ui."):
        return "ui." + name[len("pyzed.ui."):]
    return "pz." + name[len("pyzed."):]


def defaults(obj) -> dict:
    """``{param: default text}`` for a function or dataclass (``None`` when required)."""
    out = {}
    if inspect.isclass(obj) and dataclasses.is_dataclass(obj):
        for f in dataclasses.fields(obj):
            if f.default is not dataclasses.MISSING:
                out[f.name] = _value(f.default)
            elif f.default_factory is not dataclasses.MISSING:  # type: ignore[misc]
                factory = f.default_factory  # type: ignore[misc]
                out[f.name] = _value(factory()) if factory in (list, dict, set, tuple) else f"{factory.__qualname__}()"
            else:
                out[f.name] = None
        return out
    try:
        params = inspect.signature(obj).parameters.values()
    except (TypeError, ValueError):
        return out
    for p in params:
        if p.kind is inspect.Parameter.VAR_KEYWORD:
            out[p.name] = "**"
        elif p.kind is inspect.Parameter.VAR_POSITIONAL:
            out[p.name] = "*"
        else:
            out[p.name] = None if p.default is inspect.Parameter.empty else _value(p.default)
    return out


def _value(v) -> str:
    return json.dumps(v, ensure_ascii=False) if isinstance(v, str) else repr(v)


def cell(value: str) -> str:
    return value.replace("|", "\\|").replace("\n", " ")


def code_block(code: str) -> str:
    """Snippet text without the common indentation (``cleandoc`` would keep it after line 1)."""
    return textwrap.dedent(code).strip("\n")


def first_paragraph(desc: str) -> str:
    return inspect.cleandoc(desc).split("\n\n")[0].strip()


