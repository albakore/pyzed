# ------------------------------------------------------------------------------------- helpers

def text(value, lang: str):
    """A ``T(en, es)`` value (or a plain one, the same in every language) in ``lang``."""
    return value[lang] if isinstance(value, dict) and set(value) == {"en", "es"} else value


def name_of(entry: dict, lang: str) -> str:
    return text(entry["name"], lang)


_CODE_SPAN = re.compile(r"(`+)(.+?)\1", re.S)


def mdx(prose: str) -> str:
    """Escapes ``{``, ``}`` and ``<`` outside code spans so Markdown prose is valid MDX."""
    out, last = [], 0
    for m in _CODE_SPAN.finditer(prose):
        out.append(_escape(prose[last:m.start()]))
        out.append(m.group(0))
        last = m.end()
    out.append(_escape(prose[last:]))
    return "".join(out)


def _escape(chunk: str) -> str:
    chunk = chunk.replace("{", "\\{").replace("}", "\\}")
    return re.sub(r"<(?!/?kbd>)", "&lt;", chunk)


def localize_links(prose: str, lang: str) -> str:
    """English text links to ``/pyzed/...``; other languages to ``/pyzed/<lang>/...``."""
    if lang == "en":
        return prose
    return re.sub(r"\]\(/pyzed/(?!" + lang + r"/)", f"](/pyzed/{lang}/", prose)


def prose(value, lang: str) -> str:
    return mdx(localize_links(inspect.cleandoc(text(value, lang)), lang))


def sort_key(name: str) -> str:
    return unicodedata.normalize("NFKD", name.casefold()).encode("ascii", "ignore").decode()


def slugify(heading: str) -> str:
    """github-slugger, which Starlight uses for heading ids."""
    value = heading.strip().lower()
    value = re.sub(r"[^\w\- ]", "", value)
    return value.replace(" ", "-")


def heading_anchors(path: Path) -> dict:
    """``{"### `button`": "button", ...}`` for every heading of a generated reference page."""
    anchors, seen, fence = {}, {}, False
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.startswith("```"):
            fence = not fence
            continue
        m = None if fence else re.match(r"^(#{2,6}) (.+)$", line)
        if not m:
            continue
        base = slugify(re.sub(r"[`*_]", lambda c: "_" if c.group(0) == "_" else "", m.group(2)))
        n = seen.get(base, 0)
        seen[base] = n + 1
        anchors.setdefault(m.group(2).strip(), base if n == 0 else f"{base}-{n}")
    return anchors


class Api:
    """Where each public name is documented in the API reference of one language."""

    def __init__(self, lang: str):
        self.lang = lang
        self.docs = importlib.import_module(f"api_docs_{lang}")
        self.where: dict = {}
        ref = DOCS / ("reference" if lang == "en" else f"{lang}/reference")
        for page in self.docs.PAGES:
            anchors = heading_anchors(ref / f"{page['slug']}.md") if (ref / f"{page['slug']}.md").exists() else {}
            for _, items in page["sections"]:
                for name, entry in items.items():
                    short = name.rsplit(".", 1)[-1]
                    anchor = anchors.get(f"`{short}`")
                    self.where[name] = (page["slug"], anchor, entry)

    def link(self, name: str) -> str:
        slug, anchor, _ = self.where[name]
        prefix = LANGS[self.lang]["prefix"]
        return f"{prefix}/reference/{slug}/" + (f"#{anchor}" if anchor else "")


def short_name(name: str) -> str:
    """``pyzed.ui.button`` -> ``ui.button``; ``pyzed.row`` -> ``pz.row``."""
    if name.startswith("pyzed.ui."):
        return "ui." + name[len("pyzed.ui."):]
    return "pz." + name[len("pyzed."):]


def defaults(obj) -> dict:
    """``{param: default text}`` for a function or dataclass (``None`` when required)."""
    out = {}
    if inspect.isclass(obj) and dataclasses.is_dataclass(obj):
        for f in dataclasses.fields(obj):
            if f.default is not dataclasses.MISSING:
                out[f.name] = _value(f.default)
            elif f.default_factory is not dataclasses.MISSING:  # type: ignore[misc]
                factory = f.default_factory  # type: ignore[misc]
                out[f.name] = _value(factory()) if factory in (list, dict, set, tuple) else f"{factory.__qualname__}()"
            else:
                out[f.name] = None
        return out
    try:
        params = inspect.signature(obj).parameters.values()
    except (TypeError, ValueError):
        return out
    for p in params:
        if p.kind is inspect.Parameter.VAR_KEYWORD:
            out[p.name] = "**"
        elif p.kind is inspect.Parameter.VAR_POSITIONAL:
            out[p.name] = "*"
        else:
            out[p.name] = None if p.default is inspect.Parameter.empty else _value(p.default)
    return out


def _value(v) -> str:
    return json.dumps(v, ensure_ascii=False) if isinstance(v, str) else repr(v)


def cell(value: str) -> str:
    return value.replace("|", "\\|").replace("\n", " ")


def code_block(code: str) -> str:
    """Snippet text without the common indentation (``cleandoc`` would keep it after line 1)."""
    return textwrap.dedent(code).strip("\n")


def first_paragraph(desc: str) -> str:
    return inspect.cleandoc(desc).split("\n\n")[0].strip()


def render_api(name: str, api: Api, labels: dict) -> str:
    obj = gen_api.resolve(name)
    _, _, entry = api.where[name]
    out = [f"### `{short_name(name)}`\n"]
    callable_ = callable(obj)
    if callable_ and not entry.get("no_signature"):
        out.append(f"```python\n{gen_api.signature(name, obj)}\n```\n")
    desc = entry.get("desc") or gen_api.first_paragraph(getattr(obj, "__doc__", None))
    if desc:
        out.append(mdx(first_paragraph(desc)) + "\n")
    params = entry.get("params", {})
    rows = []
    if callable_ and not entry.get("docstring"):
        found = defaults(obj)
        for p in gen_api.param_names(obj):
            description = params.get(p) or api.docs.COMMON.get(p)
            if description is None:
                continue
            default = found.get(p)
            shown = f"`**{p}`" if default == "**" else f"`*{p}`" if default == "*" else f"`{p}`"
            if default in ("**", "*"):
                default_text = "—"
            elif default is None:
                default_text = f"*{labels['required']}*"
            else:
                default_text = f"`{cell(default)}`"
            rows.append(f"| {shown} | {default_text} | {cell(mdx(description.strip()))} |")
    if rows:
        out.append(f"| {labels['param']} | {labels['default']} | {labels['desc']} |\n| --- | --- | --- |\n"
                   + "\n".join(rows) + "\n")
    out.append(f"[{labels['reference']} →]({api.link(name)})\n")
    return "\n".join(out)


def tabs(name: str, alt: str, code: str, labels: dict) -> str:
    return "\n".join([
        '<Tabs syncKey="library-view">',
        f'<TabItem label="{labels["preview"]}">',
        f"<Preview name={json.dumps(name)} alt={json.dumps(alt, ensure_ascii=False)} />",
        "</TabItem>",
        f'<TabItem label="{labels["code"]}">',
        "",
        "```python",
        code_block(code),
        "```",
        "",
        "</TabItem>",
        "</Tabs>",
        "",
    ])


def imports_for(code: str) -> str:
    lines = []
    if re.search(r"\bpz\.", code):
        lines.append("import pyzed as pz")
    if re.search(r"\bui\.", code):
        lines.append("from pyzed import ui")
    if re.search(r"\bdraw\.", code):
        lines.append("from pyzed import draw")
    return "\n".join(lines)


def seo_description(blurb: str, lang: str) -> str:
    """The blurb plus the longest ``seo`` suffix that keeps it within 160 characters (search snippets)."""
    blurb = blurb.strip()
    if not blurb.endswith((".", "!", "?")):
        blurb += "."
    for suffix in LANGS[lang]["seo"]:
        if len(blurb) + len(suffix) <= 160:
            return blurb + suffix
    return blurb


def frontmatter(title: str, description: str, order: int, label: str | None = None, badge: str | None = None) -> str:
    lines = ["---", f"title: {json.dumps(title, ensure_ascii=False)}",
             f"description: {json.dumps(description, ensure_ascii=False)}", "sidebar:", f"  order: {order}"]
    if label:
        lines.append(f"  label: {json.dumps(label, ensure_ascii=False)}")
    if badge:
        lines += ["  badge:", f"    text: {json.dumps(badge, ensure_ascii=False)}", "    variant: tip"]
    return "\n".join(lines + ["---", ""])


# --------------------------------------------------------------------------------------- pages

def ordered(lang: str) -> list:
    return sorted(library_data.COMPONENTS, key=lambda e: sort_key(name_of(e, lang)))


def render_page(entry: dict, order: int, lang: str, api: Api, by_slug: dict) -> str:
    labels = LANGS[lang]
    prefix = labels["prefix"]
    name = name_of(entry, lang)
    category = text(library_data.CATEGORIES[entry["category"]], lang)
    badge = labels["new"] if entry.get("badge") == "new" else None
    main = entry["api"][0]
    body = [
        frontmatter(name, seo_description(text(entry["blurb"], lang), lang), order, label=name, badge=badge),
        f"{{/* {GENERATED} */}}",
        "",
        "import { Tabs, TabItem, LinkCard, CardGrid } from '@astrojs/starlight/components';",
        f"import Preview from '{labels['components']}/library/Preview.astro';",
        "",
        prose(entry["desc"], lang),
        "",
        f"`{short_name(main)}` · {labels['category']}: [{category}]({prefix}/library/#{slugify(category)}) · "
        f"[{labels['reference']} →]({api.link(main)})",
        "",
        tabs(entry["slug"], name, entry["preview"]["code"], labels),
    ]
    when = text(entry.get("when"), lang)
    if when:
        body += [f"## {labels['when']}", ""] + [f"- {mdx(localize_links(w, lang))}" for w in when] + [""]
    usage = code_block(entry.get("usage") or entry["preview"]["code"])
    body += [f"## {labels['usage']}", "", "```python", imports_for(usage), "", usage, "```", ""]
    examples = entry.get("examples", ())
    if examples:
        body += [f"## {labels['examples']}", ""]
        for i, ex in enumerate(examples, start=1):
            title = text(ex["title"], lang)
            body += [f"### {mdx(title)}", ""]
            if ex.get("text"):
                body += [prose(ex["text"], lang), ""]
            if ex.get("shot", True):
                body.append(tabs(f"{entry['slug']}-{i}", f"{name}: {title}", ex["code"], labels))
            else:
                body += ["```python", code_block(ex["code"]), "```", ""]
    if entry.get("notes"):
        body += [f"## {labels['tips']}", "", prose(entry["notes"], lang), ""]
    body += [f"## {labels['api']}", ""]
    for api_name in entry["api"]:
        body.append(render_api(api_name, api, labels))
    related = [by_slug[s] for s in entry.get("related", ()) if s in by_slug]
    if related:
        body += [f"## {labels['related']}", "", "<CardGrid>"]
        for other in related:
            body.append(f"<LinkCard title={json.dumps(name_of(other, lang), ensure_ascii=False)} "
                        f"description={json.dumps(text(other['blurb'], lang), ensure_ascii=False)} "
                        f"href=\"{prefix}/library/{other['slug']}/\" />")
        body += ["</CardGrid>", ""]
    return "\n".join(body).rstrip() + "\n"


def render_index(lang: str) -> str:
    labels = LANGS[lang]
    entries = ordered(lang)
    body = [
        frontmatter(labels["title"], labels["description"], 0, label=labels["overview"]),
        f"{{/* {GENERATED} */}}",
        "",
        f"import Gallery from '{labels['components']}/library/Gallery.astro';",
        "",
        localize_links(inspect.cleandoc(labels["intro"]), lang),
        "",
    ]
    for key, title in library_data.CATEGORIES.items():
        items = [e for e in entries if e["category"] == key]
        if not items:
            continue
        cards = [{"slug": e["slug"], "name": name_of(e, lang), "blurb": text(e["blurb"], lang),
                  **({"badge": labels["new"]} if e.get("badge") == "new" else {})} for e in items]
        body += [
            f"## {text(title, lang)}",
            "",
            prose(library_data.CATEGORY_INTROS[key], lang),
            "",
            f"<Gallery base=\"{labels['prefix']}/library/\" items={{{json.dumps(cards, ensure_ascii=False)}}} />",
            "",
        ]
    return "\n".join(body).rstrip() + "\n"


def build(lang: str) -> dict:
    """``{file name: content}`` for every page of ``lang``."""
    api = Api(lang)
    by_slug = {e["slug"]: e for e in library_data.COMPONENTS}
    pages = {"index.mdx": render_index(lang)}
    for order, entry in enumerate(ordered(lang), start=1):
        pages[f"{entry['slug']}.mdx"] = render_page(entry, order, lang, api, by_slug)
    return pages


# --------------------------------------------------------------------------------------- check

def problems() -> list:
    out = []
    entries = library_data.COMPONENTS
    slugs = [e["slug"] for e in entries]
    for s in {s for s in slugs if slugs.count(s) > 1}:
        out.append(f"duplicate slug: {s}")
    known = set(slugs)
    covered = {name for e in entries for name in e["api"]}
    for export in ui.__all__:
        if f"pyzed.ui.{export}" not in covered:
            out.append(f"pyzed.ui.{export} is not on any library page (add it to an entry's api)")
    apis = {lang: Api(lang) for lang in LANGS}
    required = ("slug", "name", "category", "api", "blurb", "desc", "preview")
    for e in entries:
        where = e.get("slug", "?")
        out += [f"{where}: missing {k}" for k in required if k not in e]
        if e.get("category") not in library_data.CATEGORIES:
            out.append(f"{where}: unknown category {e.get('category')!r}")
        out += [f"{where}: unknown related slug {r!r}" for r in e.get("related", ()) if r not in known]
        for name in e.get("api", ()):
            try:
                gen_api.resolve(name)
            except (AttributeError, ImportError):
                out.append(f"{where}: {name} does not exist")
                continue
            for lang, api in apis.items():
                if name not in api.where:
                    out.append(f"[{lang}] {where}: {name} is not in api_docs_{lang}.py")
                elif not api.where[name][1]:
                    out.append(f"[{lang}] {where}: no heading for {name} in the API reference (run gen_api.py)")
        stems = [where] + [f"{where}-{i}" for i, ex in enumerate(e.get("examples", ()), start=1) if ex.get("shot", True)]
        for stem in stems:
            for theme in ("dark", "light"):
                if not (ASSETS / f"{stem}.{theme}.png").exists():
                    out.append(f"{where}: missing image {stem}.{theme}.png (run library_shots.py {where})")
        for lang in LANGS:
            for key in ("blurb", "desc", "when"):
                value = e.get(key)
                if value is not None and not (isinstance(value, dict) and set(value) == {"en", "es"}):
                    out.append(f"{where}: {key} needs T(en, es)")
    return out


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="report problems and stale pages, write nothing")
    args = parser.parse_args()

    if args.check:
        issues = problems()
        for lang, labels in LANGS.items():
            for file, content in build(lang).items():
                path = labels["out"] / file
                if not path.exists() or path.read_text(encoding="utf-8") != content:
                    issues.append(f"[{lang}] {path.relative_to(DOCS)} is out of date (run gen_library.py)")
        for issue in issues:
            print(issue)
        print(f"{len(library_data.COMPONENTS)} components, {len(issues)} problems")
        return 1 if issues else 0

    for lang, labels in LANGS.items():
        out = labels["out"]
        out.mkdir(parents=True, exist_ok=True)
        pages = build(lang)
        for stale in out.glob("*.mdx"):
            if stale.name not in pages:
                stale.unlink()
        for file, content in pages.items():
            (out / file).write_text(content, encoding="utf-8")
        print(f"[{lang}] wrote {len(pages)} pages to {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
