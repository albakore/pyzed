def event_params(name: str) -> list:
    """The ``on_*`` parameters of a public name (its own events), in signature order."""
    return [p for p in gen_api.param_names(gen_api.resolve(name)) if p.startswith("on_")]


def is_component(name: str) -> bool:
    obj = gen_api.resolve(name)
    return inspect.isclass(obj) and issubclass(obj, pyzed.Component)


def handler_args(name: str, param: str) -> str:
    """What the handler of ``param`` receives, written as a call signature: ``()``, ``(text)``..."""
    shapes = library_events.HANDLERS
    for key in (f"{short_name(name)}.{param}", short_name(name) + ".*"):
        if key in shapes:
            return shapes[key]
    if is_component(name):
        return "(event)"
    return shapes.get(param, "()")


def own_events(entry: dict) -> list:
    """``(api names, param)`` for every own event of an entry's public names, once per event name.

    ``ui.button`` and ``pz.button`` both have ``on_press``: that is one event, of both names (the first
    one, usually the ``ui`` component, describes it).
    """
    found: dict = {}
    for name in entry["api"]:
        for p in event_params(name):
            found.setdefault(p, []).append(name)
    return [(names, p) for p, names in found.items()]


def event_description(name: str, param: str, api: Api) -> str:
    _, _, doc = api.where[name]
    found = doc.get("params", {}).get(param) or api.docs.COMMON.get(param)
    if found is None:
        found = text(library_events.TEXTS.get(f"{short_name(name)}.{param}", ""), api.lang)
    return found.strip()


def style_tabs(code: dict, labels: dict) -> list:
    """Imperative / declarative / functional tabs, synced across the site."""
    out = ['<Tabs syncKey="code-style">']
    for key in ("imperative", "declarative", "functional"):
        if key in code:
            out += [f'<TabItem label="{labels["styles"][key]}">', "", "```python", code_block(code[key]), "```", "",
                    "</TabItem>"]
    return out + ["</Tabs>", ""]


def render_events(entry: dict, name: str, api: Api, labels: dict, lang: str) -> list:
    """The "Events" section: how many events the component has, a table of its own and how to handle them."""
    events = own_events(entry)
    count = len(events)
    out = [f"## {labels['events']}", ""]
    if count:
        noun = labels["event_1"] if count == 1 else labels["event_n"]
        intro = labels["events_own"].format(name=name, n=count, events=noun)
    else:
        intro = labels["events_none"].format(name=name)
    common = labels["events_common"].format(common=len(pz_events.COMMON))
    out += [mdx(intro) + " " + localize_links(common, lang), ""]
    if any(is_component(n) for n in entry["api"]):
        out += [labels["events_lifecycle"], ""]
    if not count:
        return out
    several = len({n for names, _ in events for n in names}) > 1
    head = [labels["event"]] + ([labels["of"]] if several else []) + [labels["handler"], labels["when_col"]]
    out += ["| " + " | ".join(head) + " |", "|" + " --- |" * len(head)]
    for names, param in events:
        row = [f"`{param}`"] + ([", ".join(f"`{short_name(n)}`" for n in names)] if several else [])
        row += [f"`{cell(handler_args(names[0], param))}`", cell(mdx(event_description(names[0], param, api)))]
        out.append("| " + " | ".join(row) + " |")
    out += ["", labels["handler_text"], ""]
    code = library_events.EXAMPLES.get(entry["slug"])
    if code:
        out += [f"### {labels['handling']}", "", localize_links(labels["handling_text"], lang), ""]
        out += style_tabs(code, labels)
    return out


def render_api(name: str, api: Api, labels: dict) -> str:
    obj = gen_api.resolve(name)
    _, _, entry = api.where[name]
    out = [f"### `{short_name(name)}`\n"]
    callable_ = callable(obj)
    if callable_ and not entry.get("no_signature"):
        out.append(f"```python\n{gen_api.signature(name, obj)}\n```\n")
    desc = entry.get("desc") or gen_api.first_paragraph(getattr(obj, "__doc__", None))
    if desc:
        out.append(mdx(first_paragraph(desc)) + "\n")
    params = entry.get("params", {})
    rows = []
    if callable_ and not entry.get("docstring"):
        found = defaults(obj)
        for p in gen_api.param_names(obj):
            if p.startswith("on_"):  # listed in the Events section
                continue
            description = params.get(p) or api.docs.COMMON.get(p)
            if description is None:
                continue
            default = found.get(p)
            shown = f"`**{p}`" if default == "**" else f"`*{p}`" if default == "*" else f"`{p}`"
            if default in ("**", "*"):
                default_text = "—"
            elif default is None:
                default_text = f"*{labels['required']}*"
            else:
                default_text = f"`{cell(default)}`"
            rows.append(f"| {shown} | {default_text} | {cell(mdx(description.strip()))} |")
    if rows:
        out.append(f"| {labels['param']} | {labels['default']} | {labels['desc']} |\n| --- | --- | --- |\n"
                   + "\n".join(rows) + "\n")
    events = event_params(name) if callable_ else []
    if events:
        out.append(f"{labels['events']}: " + ", ".join(f"`{e}`" for e in events)
                   + f" ([{labels['events'].lower()}](#{slugify(labels['events'])})).\n")
    out.append(f"[{labels['reference']} →]({api.link(name)})\n")
    return "\n".join(out)


def tabs(name: str, alt: str, code: str, labels: dict) -> str:
    return "\n".join([
        '<Tabs syncKey="library-view">',
        f'<TabItem label="{labels["preview"]}">',
        f"<Preview name={json.dumps(name)} alt={json.dumps(alt, ensure_ascii=False)} />",
        "</TabItem>",
        f'<TabItem label="{labels["code"]}">',
        "",
        "```python",
        code_block(code),
        "```",
        "",
        "</TabItem>",
        "</Tabs>",
        "",
    ])


_MONO = re.compile(r'[=()"\[\]_.]')


def variant_stems(entry: dict):
    """``(file stem, item)`` for every variant of an entry, as library_shots.py names the images."""
    for g, group in enumerate(entry.get("variants", ()), start=1):
        for i, item in enumerate(group["items"], start=1):
            yield f"{entry['slug']}-v{g}-{i}", item


def variant_count(entry: dict) -> int:
    return sum(len(group["items"]) for group in entry.get("variants", ()))


def render_variants(entry: dict, name: str, labels: dict, lang: str) -> list:
    """The "Variants" section: a heading per group and a grid of captioned captures with their code."""
    groups = entry.get("variants", ())
    if not groups:
        return []
    out = [f"## {labels['variants']}", "",
           f":::note[{labels['shots_title']}]", labels["shots_text"], ":::", ""]
    stems = dict(variant_stems(entry))
    by_item = {id(item): stem for stem, item in stems.items()}
    for group in groups:
        out += [f"### {mdx(text(group['title'], lang))}", ""]
        if group.get("text"):
            out += [prose(group["text"], lang), ""]
        out.append("<VariantGrid>")
        for item in group["items"]:
            caption = text(item["caption"], lang)
            mono = isinstance(item["caption"], str) or bool(_MONO.search(caption) and " " not in caption)
            attrs = (f"name={json.dumps(by_item[id(item)])} caption={{{json.dumps(caption, ensure_ascii=False)}}} "
                     f"alt={{{json.dumps(f'{name}: {caption}', ensure_ascii=False)}}} "
                     f"code={json.dumps(labels['code'], ensure_ascii=False)}" + (" mono" if mono else ""))
            out += [f"<Variant {attrs}>", "", "```python", code_block(item["code"]), "```", "", "</Variant>"]
        out += ["</VariantGrid>", ""]
    return out


def imports_for(code: str) -> str:
    lines = []
    if re.search(r"\bpz\.", code):
        lines.append("import pyzed as pz")
    if re.search(r"\bui\.", code):
        lines.append("from pyzed import ui")
    if re.search(r"\bdraw\.", code):
        lines.append("from pyzed import draw")
    return "\n".join(lines)


def seo_description(blurb: str, lang: str) -> str:
    """The blurb plus the longest ``seo`` suffix that keeps it within 160 characters (search snippets)."""
    blurb = blurb.strip()
    if not blurb.endswith((".", "!", "?")):
        blurb += "."
    for suffix in LANGS[lang]["seo"]:
        if len(blurb) + len(suffix) <= 160:
            return blurb + suffix
    return blurb


def frontmatter(title: str, description: str, order: int, label: str | None = None, badge: str | None = None,
                section: dict | None = None) -> str:
    lines = ["---", f"title: {json.dumps(title, ensure_ascii=False)}",
             f"description: {json.dumps(description, ensure_ascii=False)}"]
    if section:  # the hero of a section overview (src/components/PageTitle.astro)
        lines += ["section:"] + [f"  {k}: {json.dumps(v, ensure_ascii=False)}" for k, v in section.items()]
    lines += ["sidebar:", f"  order: {order}"]
    if label:
        lines.append(f"  label: {json.dumps(label, ensure_ascii=False)}")
    if badge:
        lines += ["  badge:", f"    text: {json.dumps(badge, ensure_ascii=False)}", "    variant: tip"]
    return "\n".join(lines + ["---", ""])


