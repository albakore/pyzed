def ordered(lang: str) -> list:
    return sorted(library_data.COMPONENTS, key=lambda e: sort_key(name_of(e, lang)))


def render_page(entry: dict, order: int, lang: str, api: Api, by_slug: dict) -> str:
    labels = LANGS[lang]
    prefix = labels["prefix"]
    name = name_of(entry, lang)
    category = text(library_data.CATEGORIES[entry["category"]], lang)
    badge = labels["new"] if entry.get("badge") == "new" else None
    main = entry["api"][0]
    body = [
        frontmatter(name, seo_description(text(entry["blurb"], lang), lang), order, label=name, badge=badge),
        f"{{/* {GENERATED} */}}",
        "",
        "import { Tabs, TabItem, LinkCard, CardGrid } from '@astrojs/starlight/components';",
        f"import Preview from '{labels['components']}/library/Preview.astro';",
        *([f"import VariantGrid from '{labels['components']}/library/VariantGrid.astro';",
           f"import Variant from '{labels['components']}/library/Variant.astro';"] if entry.get("variants") else []),
        "",
        *([f":::tip[{labels['plain']}]", prose(entry["plain"], lang), ":::", ""] if entry.get("plain") else []),
        prose(entry["desc"], lang),
        "",
        f"`{short_name(main)}` · {labels['category']}: [{category}]({prefix}/library/#{slugify(category)}) · "
        f"[{labels['reference']} →]({api.link(main)})",
        "",
        tabs(entry["slug"], name, entry["preview"]["code"], labels),
    ]
    clip = entry.get("clip")
    if clip:
        body[3:3] = [f"import Media from '{labels['components']}/Media.astro';"]
        alt = json.dumps(text(clip["alt"], lang), ensure_ascii=False)
        caption = json.dumps(text(clip["caption"], lang), ensure_ascii=False)
        body += ["", f"<Media clip=\"{clip['name']}\" alt={{{alt}}} caption={{{caption}}} />", ""]
    if badge:
        body += [f":::note[{labels['new_title']}]", localize_links(labels["new_text"], lang), ":::", ""]
    when = text(entry.get("when"), lang)
    if when:
        body += [f"## {labels['when']}", ""] + [f"- {mdx(localize_links(w, lang))}" for w in when] + [""]
    usage = code_block(entry.get("usage") or entry["preview"]["code"])
    body += [f"## {labels['usage']}", "", "```python", imports_for(usage), "", usage, "```", ""]
    body += render_variants(entry, name, labels, lang)
    examples = entry.get("examples", ())
    if examples:
        body += [f"## {labels['examples']}", ""]
        for i, ex in enumerate(examples, start=1):
            title = text(ex["title"], lang)
            body += [f"### {mdx(title)}", ""]
            if ex.get("text"):
                body += [prose(ex["text"], lang), ""]
            if ex.get("shot", True):
                body.append(tabs(f"{entry['slug']}-{i}", f"{name}: {title}", ex["code"], labels))
            else:
                body += ["```python", code_block(ex["code"]), "```", ""]
    body += render_events(entry, name, api, labels, lang)
    if entry.get("notes"):
        body += [f"## {labels['tips']}", "", ":::tip", prose(entry["notes"], lang), ":::", ""]
    body += [f"## {labels['api']}", ""]
    for api_name in entry["api"]:
        body.append(render_api(api_name, api, labels))
    related = [by_slug[s] for s in entry.get("related", ()) if s in by_slug]
    if related:
        body += [f"## {labels['related']}", "", "<CardGrid>"]
        for other in related:
            body.append(f"<LinkCard title={json.dumps(name_of(other, lang), ensure_ascii=False)} "
                        f"description={json.dumps(text(other['blurb'], lang), ensure_ascii=False)} "
                        f"href=\"{prefix}/library/{other['slug']}/\" />")
        body += ["</CardGrid>", ""]
    return "\n".join(body).rstrip() + "\n"


def render_index(lang: str) -> str:
    labels = LANGS[lang]
    entries = ordered(lang)
    body = [
        frontmatter(labels["title"], labels["description"], 0, label=labels["overview"], section=labels["hero"]),
        f"{{/* {GENERATED} */}}",
        "",
        f"import Gallery from '{labels['components']}/library/Gallery.astro';",
        f"import LibraryStats from '{labels['components']}/library/LibraryStats.astro';",
        "",
    ]
    groups = [(key, text(title, lang), [e for e in entries if e["category"] == key])
              for key, title in library_data.CATEGORIES.items()]
    groups = [g for g in groups if g[2]]
    stats = [{"value": len(entries), "label": labels["components_n"]},
             {"value": sum(variant_count(e) for e in entries), "label": labels["variants_n"]},
             {"value": len(groups), "label": labels["categories_n"]}]
    chips = [{"label": title, "href": f"#{slugify(title)}", "count": len(items)} for _, title, items in groups]
    body += [
        f"<LibraryStats stats={{{json.dumps(stats, ensure_ascii=False)}}} "
        f"categories={{{json.dumps(chips, ensure_ascii=False)}}} navLabel={json.dumps(labels['title'], ensure_ascii=False)} />",
        "",
        localize_links(inspect.cleandoc(labels["intro"]), lang),
        "",
    ]
    for key, title, items in groups:
        cards = []
        for e in items:
            n = variant_count(e)
            cards.append({"slug": e["slug"], "name": name_of(e, lang), "blurb": text(e["blurb"], lang).replace("`", ""),
                          **({"badge": labels["new"]} if e.get("badge") == "new" else {}),
                          **({"count": f"{n} {labels['variant_1'] if n == 1 else labels['variants_n']}"} if n else {})})
        summary = (f"{len(items)} {labels['components_n']} · "
                   f"{sum(variant_count(e) for e in items)} {labels['variants_n']}")
        body += [
            f"## {title}",
            "",
            prose(library_data.CATEGORY_INTROS[key], lang),
            "",
            f"<Gallery base=\"{labels['prefix']}/library/\" summary={json.dumps(summary, ensure_ascii=False)} "
            f"items={{{json.dumps(cards, ensure_ascii=False)}}} />",
            "",
        ]
    return "\n".join(body).rstrip() + "\n"


def render_events_index(lang: str) -> str:
    """``library/events.mdx``: the common events, what handlers get and the events of every component."""
    labels = LANGS[lang]
    inv = labels["inv"]
    entries = ordered(lang)
    common = len(pz_events.COMMON)
    counted = [(e, own_events(e)) for e in entries]
    total = sum(len(ev) for _, ev in counted)
    body = [
        frontmatter(inv["title"], inv["description"], 0.5, label=inv["label"]),
        f"{{/* {GENERATED} */}}",
        "",
        localize_links(inspect.cleandoc(inv["intro"]).format(common=common, components=len(entries), total=total),
                       lang),
        "",
        f"## {inv['common']}",
        "",
        inv["common_text"],
        "",
        f"| {inv['group']} | {labels['event']} | {labels['when_col']} |",
        "| --- | --- | --- |",
    ]
    groups = library_events.GROUPS
    texts = library_events.COMMON_TEXT
    for info in pz_events.CATALOG.values():
        doc = gen_api.rst_to_md(info.doc) if lang == "en" else texts[info.name]
        body.append(f"| {text(groups[info.category], lang)} | `{info.name}` | {cell(mdx(doc))} |")
    body += ["", f"### {inv['field']}", "", f"| {labels['param']} | {labels['desc']} |", "| --- | --- |"]
    for field, value in library_events.EVENT_FIELDS:
        body.append(f"| {field} | {cell(mdx(text(value, lang)))} |")
    body += ["", f"## {inv['handlers']}", "", inv["handlers_text"], "",
             f"| {inv['shape']} | {labels['desc']} | {inv['examples']} |", "| --- | --- | --- |"]
    shapes: dict = {}
    for e, events in counted:
        for names, param in events:
            shapes.setdefault(handler_args(names[0], param), []).append(f"{short_name(names[0])}({param}=)")
    for shape, where in sorted(shapes.items(), key=lambda kv: -len(kv[1])):
        meaning = library_events.SHAPES.get(shape)
        if meaning is None or len(where) < 2:
            continue
        sample = ", ".join(f"`{w}`" for w in where[:4]) + ("…" if len(where) > 4 else "")
        body.append(f"| `{cell(shape)}` | {cell(mdx(text(meaning, lang)))} | {sample} |")
    body += ["", f"## {inv['by']}", "", inv["by_text"].format(common=common), "",
             f"| {inv['component']} | {inv['own']} | {inv['total']} | {inv['list']} |", "| --- | --- | --- | --- |"]
    for e, events in sorted(counted, key=lambda c: (-len(c[1]), sort_key(name_of(c[0], lang)))):
        extra = 2 if any(is_component(n) for n in e["api"]) else 0
        names = ", ".join(dict.fromkeys(f"`{p}`" for _, p in events)) or "—"
        link = f"[{name_of(e, lang)}]({labels['prefix']}/library/{e['slug']}/#{slugify(labels['events'])})"
        body.append(f"| {link} | {len(events)} | {len(events) + common + extra} | {names} |")
    body += ["", localize_links(inv["next"], lang), ""]
    return "\n".join(body).rstrip() + "\n"


def build(lang: str) -> dict:
    """``{file name: content}`` for every page of ``lang``."""
    api = Api(lang)
    by_slug = {e["slug"]: e for e in library_data.COMPONENTS}
    pages = {"index.mdx": render_index(lang), "events.mdx": render_events_index(lang)}
    for order, entry in enumerate(ordered(lang), start=1):
        pages[f"{entry['slug']}.mdx"] = render_page(entry, order, lang, api, by_slug)
    return pages


