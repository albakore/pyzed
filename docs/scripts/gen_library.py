def problems() -> list:
    out = []
    entries = library_data.COMPONENTS
    slugs = [e["slug"] for e in entries]
    for s in {s for s in slugs if slugs.count(s) > 1}:
        out.append(f"duplicate slug: {s}")
    known = set(slugs)
    covered = {name for e in entries for name in e["api"]}
    for export in ui.__all__:
        if f"pyzed.ui.{export}" not in covered:
            out.append(f"pyzed.ui.{export} is not on any library page (add it to an entry's api)")
    apis = {lang: Api(lang) for lang in LANGS}
    used: set = set()
    required = ("slug", "name", "category", "api", "blurb", "desc", "preview")
    manifest = json.loads((HERE.parent / "public" / "media" / "manifest.json").read_text(encoding="utf-8"))
    clips = {c["name"] for c in manifest["clips"]}
    media_file = CLIPS / "manifest.json"
    media = json.loads(media_file.read_text(encoding="utf-8")) if media_file.exists() else {}
    for e in entries:
        where = e.get("slug", "?")
        out += [f"{where}: missing {k}" for k in required if k not in e]
        if e.get("category") not in library_data.CATEGORIES:
            out.append(f"{where}: unknown category {e.get('category')!r}")
        out += [f"{where}: unknown related slug {r!r}" for r in e.get("related", ()) if r not in known]
        for name in e.get("api", ()):
            try:
                gen_api.resolve(name)
            except (AttributeError, ImportError):
                out.append(f"{where}: {name} does not exist")
                continue
            for lang, api in apis.items():
                if name not in api.where:
                    out.append(f"[{lang}] {where}: {name} is not in api_docs_{lang}.py")
                elif not api.where[name][1]:
                    out.append(f"[{lang}] {where}: no heading for {name} in the API reference (run gen_api.py)")
        stems = [where] + [f"{where}-{i}" for i, ex in enumerate(e.get("examples", ()), start=1) if ex.get("shot", True)]
        stems += [stem for stem, _ in variant_stems(e)]
        for stem in stems + [f"{where}.thumb"]:
            for theme in ("dark", "light"):
                for name in (f"{stem}.{theme}.webp", f"{stem}.{theme}.still.webp"):
                    used.add(name)
                    if not (CLIPS / name).exists():
                        out.append(f"{where}: missing clip {name} (run library_shots.py {where})")
                key = f"{stem}.{theme}"
                if key not in media:
                    out.append(f"{where}: {key} is not in public/library/manifest.json (run library_shots.py {where})")
                elif media[key].get("frames", 0) < 2:
                    out.append(f"{where}: {key}.webp is not animated")
        clip = e.get("clip")
        if clip and clip.get("name") not in clips:
            out.append(f"{where}: unknown clip {clip.get('name')!r} (not in docs/public/media/manifest.json)")
        if not e.get("plain"):
            out.append(f"{where}: missing plain (add it to PLAIN)")
        for g, group in enumerate(e.get("variants", ()), start=1):
            for value in [group["title"], group.get("text")] + [i["caption"] for i in group["items"]]:
                if value is not None and not isinstance(value, str) and not (isinstance(value, dict) and set(value) == {"en", "es"}):
                    out.append(f"{where}: variant group {g} needs T(en, es) or a plain string")
        for lang in LANGS:
            for key in ("blurb", "desc", "when", "plain"):
                value = e.get(key)
                if value is not None and not (isinstance(value, dict) and set(value) == {"en", "es"}):
                    out.append(f"{where}: {key} needs T(en, es)")
        for names, param in own_events(e):
            for lang, api in apis.items():
                if names[0] in api.where and not event_description(names[0], param, api):
                    out.append(f"[{lang}] {where}: {short_name(names[0])}({param}=) has no description "
                               "(api_docs or library_events.TEXTS)")
        if own_events(e) and e["slug"] not in library_events.EXAMPLES:
            out.append(f"{where}: no event examples (add them to library_events.EXAMPLES)")
    for orphan in sorted(p.name for p in CLIPS.glob("*.webp") if p.name not in used):
        out.append(f"unused clip {orphan} (run library_shots.py --prune)")
    for key in sorted(k for k in media if f"{k}.webp" not in used):
        out.append(f"public/library/manifest.json lists {key}, which no entry uses")
    return out


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="report problems and stale pages, write nothing")
    args = parser.parse_args()

    if args.check:
        issues = problems()
        for lang, labels in LANGS.items():
            for file, content in build(lang).items():
                path = labels["out"] / file
                if not path.exists() or path.read_text(encoding="utf-8") != content:
                    issues.append(f"[{lang}] {path.relative_to(DOCS)} is out of date (run gen_library.py)")
        if library_sidebar.stale():
            issues.append(f"{library_sidebar.OUT.relative_to(DOCS.parent.parent.parent)} is out of date (run gen_library.py)")
        for issue in issues:
            print(issue)
        variants = sum(variant_count(e) for e in library_data.COMPONENTS)
        print(f"{len(library_data.COMPONENTS)} components, {variants} variants, {len(issues)} problems")
        return 1 if issues else 0

    for lang, labels in LANGS.items():
        out = labels["out"]
        out.mkdir(parents=True, exist_ok=True)
        pages = build(lang)
        for stale in out.glob("*.mdx"):
            if stale.name not in pages:
                stale.unlink()
        for file, content in pages.items():
            (out / file).write_text(content, encoding="utf-8")
        print(f"[{lang}] wrote {len(pages)} pages to {out}")
    library_sidebar.write()
    return 0


if __name__ == "__main__":
    sys.exit(main())
