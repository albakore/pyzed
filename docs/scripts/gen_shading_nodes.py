def build() -> Dict[Path, str]:
    """Every page, by path."""
    out: Dict[Path, str] = {}
    for lang, L in LANGS.items():
        out[L["out"] / "index.mdx"] = index(lang)
        for order, p in enumerate(data.PAGES, start=1):
            out[L["out"] / f"{p[0]}.mdx"] = page(*p, order, lang)
    return out


def _png(path: Path) -> None:
    """Writes a 1×1 PNG, the image the Sample texture example reads."""
    import struct
    import zlib

    def chunk(kind: bytes, body: bytes) -> bytes:
        return struct.pack(">I", len(body)) + kind + body + struct.pack(">I", zlib.crc32(kind + body) & 0xFFFFFFFF)

    ihdr = struct.pack(">IIBBBBB", 1, 1, 8, 2, 0, 0, 0)
    path.write_bytes(b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", ihdr) + chunk(b"IDAT", zlib.compress(b"\x00\xff\x80\x00"))
                     + chunk(b"IEND", b""))


def check_examples() -> List[str]:
    """Compiles every example (in a folder with the image they read); returns the problems."""
    import os
    import tempfile

    problems: List[str] = []
    here = os.getcwd()
    with tempfile.TemporaryDirectory() as tmp:
        _png(Path(tmp) / "photo.png")
        os.chdir(tmp)
        try:
            _check_examples(problems)
        finally:
            os.chdir(here)
    return problems


def _check_examples(problems: List[str]) -> None:
    for type_id in N.TYPES:
        if type_id not in data.NODES:
            problems.append(f"{type_id}: no entry in shading_nodes_data.NODES")
    for type_id, info in data.NODES.items():
        if type_id not in N.TYPES:
            problems.append(f"{type_id}: not a node type")
            continue
        code = info.get("code")
        if not code:
            continue
        scope: Dict[str, Any] = {}
        try:
            exec(PRELUDE + code, scope)  # noqa: S102 - our own examples
            g = scope["g"]
            if g.output_node is None:
                problems.append(f"{type_id}: the example has no Output node")
            if not any(n.type == type_id for n in g.nodes.values()):
                problems.append(f"{type_id}: the example doesn't use the node")
            compiled = g.compile()
            if compiled.errors:
                problems.append(f"{type_id}: {compiled.errors}")
        except Exception as e:  # noqa: BLE001
            problems.append(f"{type_id}: {type(e).__name__}: {e}")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="fail if a page is out of date or an example breaks")
    args = parser.parse_args()
    problems = check_examples()
    pages = build()
    if args.check:
        for path, text in pages.items():
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                problems.append(f"{path.relative_to(ROOT)} is out of date: run python docs/scripts/gen_shading_nodes.py")
        for problem in problems:
            print(problem, file=sys.stderr)
        return 1 if problems else 0
    for problem in problems:
        print(problem, file=sys.stderr)
    for path, text in pages.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
    print(f"wrote {len(pages)} pages")
    return 1 if problems else 0


