PRELUDE = 'from pyzed import shading\n\ng = shading.Graph("demo")\n'


def tr(text: str, lang: str) -> str:
    """``text`` in ``lang`` (the catalog's own Spanish texts)."""
    return ES.get(text, text) if lang == "es" and text else text


def prose(text: str) -> str:
    """``text`` made safe for MDX: ``<``, ``{`` and ``}`` outside code spans are escaped."""
    parts = text.split("`")
    for i in range(0, len(parts), 2):
        parts[i] = parts[i].replace("<", "&lt;").replace("{", "&#123;").replace("}", "&#125;")
    return "`".join(parts)


def slug(text: str) -> str:
    """The id Starlight gives a heading (github-slugger)."""
    text = text.lower()
    text = re.sub(r"[^\w\- ]", "", text)
    return text.replace(" ", "-")


def method(preset: N.Preset) -> str:
    """The ``Graph`` method that adds a sidebar entry."""
    if preset.type == "math" and preset.params:
        return preset.params["op"]
    if preset.type == "func" and preset.params:
        return preset.params["op"]
    if not preset.params:
        return preset.type
    return preset.title.lower().replace(" ", "_")


def fmt_value(value: Any) -> str:
    if isinstance(value, bool):
        return "`true`" if value else "`false`"
    if isinstance(value, float):
        return f"`{value:g}`"
    if isinstance(value, (list, tuple)):
        if value and isinstance(value[0], (list, tuple)):  # gradient stops
            return ", ".join(f"`{p:g}` {c}" for p, c in value)
        return "`(" + ", ".join(f"{v:g}" if isinstance(v, float) else str(v) for v in value) + ")`"
    if value in (None, ""):
        return "—"
    return f"`{value}`"


def fmt_default(port: N.Input, lang: str) -> str:
    if isinstance(port.default, str) and port.default in N.CONTEXT:
        return f"*{tr(N.CONTEXT_LABELS[port.default], lang)}* ({LANGS[lang]['context']})"
    if port.default is None:
        return "— " + f"({LANGS[lang]['none']})" if port.type != "texture" else "—"
    return fmt_value(port.default)


def port_name(port: Any, lang: str) -> str:
    """The port's name in code, and how its node labels it when that differs."""
    shown = tr(port.title, lang)
    return f"`{port.name}`" + (f" · {shown}" if shown != port.name else "")


def _table(head: List[str], rows: List[List[str]]) -> List[str]:
    out = ["| " + " | ".join(head) + " |", "| " + " | ".join("---" for _ in head) + " |"]
    out += ["| " + " | ".join(cell.replace("|", "\\|") for cell in row) + " |" for row in rows]
    return out


def image_name(type_id: str) -> str:
    """The name a page imports a node's capture as."""
    return "node_" + re.sub(r"\W", "_", type_id)


def image_imports(types: List[N.NodeType], lang: str) -> List[str]:
    """The imports of the captures of ``types``; fails when one is missing."""
    up = LANGS[lang]["up"]
    out = []
    for nt in types:
        path = ROOT / "docs" / "src" / "assets" / "shading" / "nodes" / f"{nt.id}.png"
        if not path.exists():
            raise SystemExit(f"missing capture: {path.relative_to(ROOT)}")
        out.append(f"import {image_name(nt.id)} from '{up}/assets/shading/nodes/{nt.id}.png';")
    return out


def node_section(nt: N.NodeType, lang: str) -> List[str]:
    L = LANGS[lang]
    info = data.NODES[nt.id]
    title = tr(nt.title, lang)
    lines = [f"### {title}", ""]
    meta = f"`{nt.id}` · {tr(nt.category, lang)} · `g.{nt.id}(...)`"
    if title != nt.title:
        meta = f"*{nt.title}* · " + meta
    alt = L["alt"].format(title=title).replace('"', "&quot;")
    lines += [meta, "", prose(tr(nt.description, lang)), "",
              f'<Media src={{{image_name(nt.id)}}} alt="{alt}" size="small" plain />', "", prose(info[lang]), ""]
    if nt.inputs:
        lines += _table([L["input"], L["type"], L["default"]],
                        [[port_name(p, lang), f"`{p.type}`", fmt_default(p, lang)] for p in nt.inputs]) + [""]
    if nt.outputs:
        lines += _table([L["output"], L["type"]], [[port_name(o, lang), f"`{o.type}`"] for o in nt.outputs]) + [""]
    if nt.params:
        rows = []
        for p in nt.params:
            values = ", ".join(f"`{o}`" for o in p.options) if p.options else f"`{p.kind}`"
            rows.append([f"`{p.name}`", values, fmt_value(p.default)])
        lines += _table([L["setting"], L["values"], L["default"]], rows) + [""]
    if nt.id in L["dynamic"]:
        lines += [L["dynamic"][nt.id], ""]
    presets = [p for p in N.PRESETS if p.type == nt.id]
    if len(presets) > 1 or (presets and presets[0].params):
        lines += [f"**{L['entries']}**", ""]
        lines += _table([L["entry"], L["does"], L["python"]],
                        [[prose(tr(p.title, lang)), prose(tr(p.description, lang)), f"`g.{method(p)}(...)`"] for p in presets])
        lines += [""]
    if info.get("code"):
        lines += [f"```python title=\"{L['example']}\"", info["code"], "```", ""]
    note = data.EXAMPLE_NOTE.get(nt.id)
    if note:
        lines += [note[0 if lang == "en" else 1], ""]
    return lines


def page(slug_: str, en_title: str, es_title: str, en_desc: str, es_desc: str, categories: Any, order: int,
         lang: str) -> str:
    L = LANGS[lang]
    title = en_title if lang == "en" else es_title
    desc = en_desc if lang == "en" else es_desc
    by_cat = defaultdict(list)
    for nt in N.TYPES.values():
        by_cat[nt.category].append(nt)
    lines = [
        "---", f"title: {json.dumps(title, ensure_ascii=False)}", f"description: {json.dumps(desc, ensure_ascii=False)}",
        "sidebar:", f"  order: {order}", "---", "", f"{{/* {GENERATED} */}}", "",
        "import { Aside } from '@astrojs/starlight/components';",
        f"import Media from '{L['up']}/components/Media.astro';",
        *image_imports([nt for cat in categories for nt in by_cat[cat]], lang), "",
        L["intro"], "", "```python", PRELUDE.rstrip(), "```", "",
    ]
    for cat in categories:
        lines += [f"## {tr(cat, lang)}", "", data.CATEGORY_TEXT[cat][0 if lang == "en" else 1], ""]
        for nt in by_cat[cat]:
            lines += node_section(nt, lang)
    lines += [f'<Aside type="tip" title="{L["generated_title"]}">', L["generated"], "</Aside>", "",
              f"**{L['see']}:** {L['see_items']}", ""]
    return "\n".join(lines)


def index(lang: str) -> str:
    L = LANGS[lang]
    pre = L["prefix"]
    by_cat = defaultdict(list)
    for nt in N.TYPES.values():
        by_cat[nt.category].append(nt)
    page_of = {cat: p for p in data.PAGES for cat in p[5]}
    anchors: Dict[str, str] = {}
    for p in data.PAGES:  # the ids of a page's headings, in order, as the slugger numbers repeats
        seen: Dict[str, int] = defaultdict(int)
        for cat in p[5]:
            for text, type_id in [(tr(cat, lang), None)] + [(tr(nt.title, lang), nt.id) for nt in by_cat[cat]]:
                base = slug(text)
                anchor = base if not seen[base] else f"{base}-{seen[base]}"
                seen[base] += 1
                if type_id:
                    anchors[type_id] = anchor
    rows = []
    for cat in N.CATEGORIES:
        p = page_of[cat]
        links = ", ".join(f"[{tr(nt.title, lang)}]({pre}/shading/nodes/{p[0]}/#{anchors[nt.id]})"
                          for nt in by_cat[cat])
        rows.append([f"**{tr(cat, lang)}**", links])
    cards = ",\n".join(
        "\t\t{ title: %s, text: %s, href: '%s/shading/nodes/%s/', icon: 'puzzle', tag: '%d' }"
        % (json.dumps(p[1] if lang == "en" else p[2], ensure_ascii=False),
           json.dumps(p[3] if lang == "en" else p[4], ensure_ascii=False), pre, p[0],
           sum(len(by_cat[c]) for c in p[5]))
        for p in data.PAGES)
    text = (INDEX_EN if lang == "en" else INDEX_ES).format(
        generated=GENERATED, count=len(N.TYPES), entries=len(N.PRESETS), cards=cards,
        table="\n".join(_table(["", ""], rows)), pre=pre)
    return text


