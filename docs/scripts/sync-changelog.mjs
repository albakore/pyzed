// Reads ../CHANGELOG.md and generates:
//   src/content/docs/changelog.md      the "What's new" page (English, site root)
//   src/content/docs/es/changelog.md   the same page in Spanish
//   src/generated/release.json         the latest stable release (used by the header and home page)
// Runs before `astro dev` and `astro build` (see package.json).
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..');
const source = resolve(root, '..', 'CHANGELOG.md');

const text = readFileSync(source, 'utf8').replace(/\r\n/g, '\n');

// Accepted headings: "## [0.2.0] - 2026-11-02", "## 0.2.0 (2026-11-02)", "## v0.2.0".
const HEADING = /^## +\[?v?(\d[^\]\s(]*)\]?(?:[^\d\n]*(\d{4}-\d{2}-\d{2}))?.*$/gm;
const PRERELEASE = /(-|a\d|b\d|rc|dev)/i;

const releases = [];
for (const match of text.matchAll(HEADING)) {
	const version = match[1];
	releases.push({ version, date: match[2] ?? null, stable: !PRERELEASE.test(version), index: match.index });
}
const latestStable = releases.find((r) => r.stable) ?? null;
const latest = releases[0] ?? null;

// Body: drop the "# Changelog" title and the intro up to the first release.
const firstSection = text.search(/^## /m);
let body = firstSection >= 0 ? text.slice(firstSection) : '';
// Drop an empty "Unreleased" section.
body = body.replace(/^## +\[?(Unreleased|Sin publicar)\]?\s*\n(?=## |\s*$)/im, '');
const LABELS = {
	en: {
		file: 'src/content/docs/changelog.md',
		title: "What's new",
		description: 'Changes, improvements, fixes and breaking changes in every Pyzed release.',
		stable: 'Latest stable',
		pre: 'Pre-release',
		latest: (v, d) => `The latest stable release is **${v}**${d ? ` (${d})` : ''}.`,
		none: 'There is no stable release yet.',
		github: 'Release notes are also on [GitHub Releases](https://github.com/albakore/pyzed/releases).',
		generated: 'Generated by docs/scripts/sync-changelog.mjs from CHANGELOG.md. Do not edit by hand.',
	},
	es: {
		file: 'src/content/docs/es/changelog.md',
		title: 'Novedades',
		description: 'Cambios, mejoras, correcciones y breaking changes de cada versión de Pyzed.',
		stable: 'Última estable',
		pre: 'Preliminar',
		latest: (v, d) => `La última versión estable es **${v}**${d ? ` (${d})` : ''}.`,
		none: 'Todavía no hay una versión estable publicada.',
		github: 'Las notas de cada versión también están en [GitHub Releases](https://github.com/albakore/pyzed/releases).',
		generated: 'Archivo generado por docs/scripts/sync-changelog.mjs a partir de CHANGELOG.md. No lo edites a mano.',
	},
};

for (const t of Object.values(LABELS)) {
	// Tag the latest stable release and the pre-releases.
	const tagged = body.replace(HEADING, (line, version) => {
		if (latestStable && version === latestStable.version) return `${line}\n\n<span class="release-tag stable">${t.stable}</span>`;
		if (PRERELEASE.test(version)) return `${line}\n\n<span class="release-tag pre">${t.pre}</span>`;
		return line;
	});
	const intro = latestStable
		? `${t.latest(latestStable.version, latestStable.date)}\n\n` +
			'```bash\npip install --upgrade pyzed-ui==' + latestStable.version + '\n```\n'
		: `${t.none}\n`;
	const page = `---
title: ${JSON.stringify(t.title)}
description: ${JSON.stringify(t.description)}
editUrl: https://github.com/albakore/pyzed/edit/main/CHANGELOG.md
tableOfContents:
  maxHeadingLevel: 2
---

<!-- ${t.generated} -->

${intro}
${t.github}

${tagged.trim()}
`;
	mkdirSync(dirname(resolve(root, t.file)), { recursive: true });
	writeFileSync(resolve(root, t.file), page);
}

mkdirSync(resolve(root, 'src/generated'), { recursive: true });
writeFileSync(
	resolve(root, 'src/generated/release.json'),
	JSON.stringify({ latestStable, latest, releases: releases.map(({ index, ...r }) => r) }, null, '\t') + '\n',
);
console.log(`changelog: ${releases.length} releases; latest stable: ${latestStable?.version ?? 'none'}`);
