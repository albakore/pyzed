"""Writes python/pyzed/_core.pyi: type stubs for the Rust extension, so editors and type checkers see it.

    maturin develop --release
    python scripts/gen_stubs.py            # writes the stub
    python scripts/gen_stubs.py --check    # fails if it is out of date

Signatures come from ``inspect`` (PyO3 exposes them) and docstrings from the extension itself, so the
stub always matches the code. Parameters are typed ``Any``; the Python package around it is typed.
"""

from __future__ import annotations

import argparse
import inspect
import keyword
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
STUB = ROOT / "python" / "pyzed" / "_core.pyi"
HEADER = '"""Type stubs for ``pyzed._core``, the Rust extension. Generated by scripts/gen_stubs.py."""\n\n'


def params(obj, skip_self: bool = False) -> str:
    try:
        sig = inspect.signature(obj)
    except (TypeError, ValueError):
        return "*args: Any, **kwargs: Any"
    out, star = [], False
    items = list(sig.parameters.values())
    if skip_self and items and items[0].name in ("self", "cls", "$self", "$cls"):
        items = items[1:]
    for p in items:
        name = p.name.lstrip("$")
        if keyword.iskeyword(name):
            name += "_"
        if p.kind is p.VAR_POSITIONAL:
            out.append(f"*{name}: Any")
            star = True
        elif p.kind is p.VAR_KEYWORD:
            out.append(f"**{name}: Any")
        else:
            if p.kind is p.KEYWORD_ONLY and not star:
                out.append("*")
                star = True
            out.append(f"{name}: Any" + (" = ..." if p.default is not p.empty else ""))
        if p.kind is p.POSITIONAL_ONLY and (items.index(p) + 1 == len(items)
                                           or items[items.index(p) + 1].kind is not p.POSITIONAL_ONLY):
            out.append("/")
    return ", ".join(out)


def doc(obj, indent: str) -> str:
    text = inspect.getdoc(obj) or ""
    if not text:
        return ""
    text = text.replace("\\", "\\\\").replace('"""', '\\"\\"\\"')
    lines = text.splitlines()
    body = "\n".join((indent + line) if line.strip() else "" for line in lines)
    return f'{indent}"""{body.lstrip()}\n{indent}"""\n' if len(lines) > 1 else f'{indent}"""{text}"""\n'


def function(name: str, obj, indent: str = "", method: bool = False) -> str:
    text = doc(obj, indent + "    ")
    head = f"{indent}def {name}({'self, ' if method else ''}{params(obj, method)}) -> Any:".replace("(self, )", "(self)")
    return f"{head}\n{text}{indent}    ...\n" if text else f"{head} ...\n"


def klass(name: str, cls) -> str:
    out = [f"class {name}:\n"]
    text = doc(cls, "    ")
    if text:
        out.append(text)
    body = []
    if "__init__" in vars(cls) or "__new__" in vars(cls) or getattr(cls, "__text_signature__", None):
        body.append(f"    def __init__(self, {params(cls)}) -> None: ...\n".replace("(self, )", "(self)"))
    for attr, value in sorted(vars(cls).items()):
        if attr.startswith("_"):
            continue
        if isinstance(value, (staticmethod, classmethod)):
            body.append(f"    @{type(value).__name__}\n" + function(attr, value.__func__, "    "))
        elif inspect.isroutine(value):
            kind = type(value).__name__
            if kind in ("builtin_function_or_method",):  # a staticmethod exposed by PyO3
                body.append("    @staticmethod\n" + function(attr, value, "    "))
            elif kind == "classmethod_descriptor":
                body.append("    @classmethod\n" + function(attr, getattr(cls, attr), "    ").replace("(", "(cls, ", 1)
                            .replace("(cls, )", "(cls)"))
            else:
                body.append(function(attr, value, "    ", method=True))
        elif inspect.isdatadescriptor(value) or isinstance(value, property):
            body.append(f"    {attr}: Any\n")
        else:
            body.append(f"    {attr}: {type(value).__name__ if isinstance(value, (int, float, str, bool)) else 'Any'}\n")
    out.extend(body or ["    ...\n"])
    return "".join(out)


def render() -> str:
    from pyzed import _core

    parts = [HEADER, "from typing import Any\n\n"]
    for name in sorted(n for n in dir(_core) if not n.startswith("_")):
        obj = getattr(_core, name)
        if inspect.isclass(obj):
            parts.append("\n" + klass(name, obj) + "\n")
        elif callable(obj):
            parts.append(function(name, obj))
        else:
            parts.append(f"{name}: Any\n")
    return "".join(parts).rstrip("\n") + "\n"


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="fail if the stub is out of date")
    args = parser.parse_args(argv)
    text = render()
    if args.check:
        if not STUB.exists() or STUB.read_text(encoding="utf-8") != text:
            print(f"{STUB.relative_to(ROOT)} is out of date: run python scripts/gen_stubs.py", file=sys.stderr)
            return 1
        return 0
    STUB.write_text(text, encoding="utf-8")
    print(f"Wrote {STUB.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
